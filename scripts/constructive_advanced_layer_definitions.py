_KNOWN = {definition.name: definition for definition in ALL_BERTRAND_DEFINITIONS}
_SEEN_IDS = {definition.stable_id for definition in ALL_BERTRAND_DEFINITIONS}
if len(_KNOWN) != len(ALL_BERTRAND_DEFINITIONS) or len(_SEEN_IDS) != len(_KNOWN):
    raise ValueError("the reviewed immutable base definition registry repeats an identity")
for definition in NEXT_LAYER_DEFINITIONS:
    if (
        definition.name in _KNOWN
        or definition.stable_id in _SEEN_IDS
        or NEXT_LAYER_DEFINITIONS_BY_NAME[definition.name] is not definition
    ):
        raise ValueError("an immutable Alpha-v20 definition lost its exact shared identity")
    if len(set(definition.conceptual_dependencies)) != len(definition.conceptual_dependencies):
        raise ValueError("an immutable Alpha-v20 definition repeats a dependency")
    if not set(definition.conceptual_dependencies) <= set(_KNOWN):
        raise ValueError("an immutable Alpha-v20 definition has an unknown or cyclic dependency")
    _KNOWN[definition.name] = definition
    _SEEN_IDS.add(definition.stable_id)

for offset, definition in enumerate(ADVANCED_LAYER_DEFINITIONS, start=12):
    if definition.stable_id != f"ND{offset:04d}":
        raise ValueError("advanced definition stable identifiers must be contiguous and additive")
    if definition.name in _KNOWN or definition.stable_id in _SEEN_IDS:
        raise ValueError("advanced definitions repeat an immutable reviewed name or stable identity")
    dependencies = definition.conceptual_dependencies
    if len(dependencies) != len(set(dependencies)):
        raise ValueError("an advanced definition repeats a conceptual dependency")
    if not set(dependencies) <= set(_KNOWN):
        raise ValueError("an advanced definition has an unknown, forward or circular dependency")
    _KNOWN[definition.name] = definition
    _SEEN_IDS.add(definition.stable_id)

