host = NativeHost(worker.SOURCE)
deadline = time.monotonic() + 20
cases = []
for identifier, title, difficulty, truth, formula, watch, evidence in CASES:
    admission = host.admit(formula, deadline=deadline)
    # The same formula also fits the unchanged Symbolic fallback admission.
    worker.validate_request("search", {"theorem": formula, "search_mode": "symbolic",
        "search_profile": "standard", "max_model_calls": 16, "beam_width": 4})
    cases.append({"id": identifier, "title": title, "difficulty_for_current_system": difficulty,
        "expected_truth_over_naturals": truth, "theorem": formula, "watch_for": watch,
        "prior_evidence": evidence, "native_admission": admission})
host.verify_sources()
