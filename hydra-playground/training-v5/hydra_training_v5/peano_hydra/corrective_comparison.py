"""A fresh four-origin PRIMARY32 experiment, never an old-checkpoint conversion.

Preserved training origins are authenticated in their own pinned source bundle.
Only the new corrective preparation is regenerated by the optimized engine.
All four models then use the same V4 authority, goals, seeds and search budget.
This is an exposed development ablation, not an unseen discovery benchmark.
"""
