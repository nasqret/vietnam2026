@dataclass(frozen=True, slots=True)
class OriginReceipt:
    request: OriginRequest
    path: Path
    sha256: str

    def load(self):
        return load_origin_receipt(self.path, expected_receipt_sha256=self.sha256, request=self.request)


def _sources() -> dict[str, str]:
    sources = comparison._sources()
    for name in SOURCE_FILES:
        sources[name] = hashlib.sha256(shared._read_regular(
            ROOT / name, maximum=2 * 1024**2, description="corrective execution source"
        )).hexdigest()
    _require(len(sources) <= capacity.MAX_SOURCE_FILES, "corrective execution source inventory exceeds bound")
    return dict(sorted(sources.items()))


def _preserved(reference: OriginReceipt, role: str):
    _require(type(reference) is OriginReceipt and role in {"catalog", "scaled"}, "invalid preserved-origin reference")
    _require(reference.request.source_commit == PRESERVED_SOURCE_COMMIT
             and reference.request.preparation_manifest_sha256 == PREPARATION_MANIFEST_SHA256[role],
             "preserved source or preparation differs from this experiment's exact original anchor")
    verified = reference.load()
    origin = verified.origin
    expected = CATALOG_MANIFEST_SHA256 if role == "catalog" else SCALED_MANIFEST_SHA256
    _require(origin["adapter_manifest_sha256"] == expected,
             "preserved adapter differs from this experiment's explicit original anchor")
    _require(origin["training_authority_profile"] == (None if role == "catalog" else AUTHORITY_PRIMITIVE_PROFILE),
             "preserved training authority was relabelled")
    return verified


@dataclass(frozen=True, slots=True)
class CorrectivePlan:
    execution: capacity.CapacityPlan
    catalog: OriginReceipt
    scaled: OriginReceipt
    _catalog_json: str
    _scaled_json: str
    _sources_json: str

    @property
    def model(self):
        return self.execution.model

    @property
    def catalog_origin(self):
        return json.loads(self._catalog_json)

    @property
    def scaled_origin(self):
        return json.loads(self._scaled_json)

    def cohort(self, name: str):
        _require(name == "primary", "corrective comparison has only its fixed PRIMARY32 panel")
        return self.execution

    def to_dict(self):
        execution = self.execution.to_dict()
        contract = {key: execution[key] for key in (
            "version", "epoch_sha256", "edition_identity_sha256", "environment", "model",
            "authority_profile", "prompt_contract", "decoder_profile", "profile_sha256",
        )}
        contract["tokenizer"] = self.catalog_origin["artifacts"]["tokenizer"]
        contract["contract_sha256"] = _digest(contract)
        sources = json.loads(self._sources_json)
        # This is a separate execution statement. Neither original manifest
        # nor origin digest is changed to match the new engine's identity.
        binding = execution_binding(source_root=ROOT, source_files=sources, contract=contract)
        record = {
            "schema": PLAN_SCHEMA, "claim_boundary": CLAIM,
            "development_only": True, "public_correlated_exposed_data": True,
            "research_claim_eligible": False, "sealed_benchmark": False,
            "independent_discoveries": False, "historical_checkpoint_reuse_allowed": False,
            "roles": list(ROLES), "goal_count_per_role": GOAL_COUNT, "total_goal_records": TOTAL_GOALS,
            "goals": list(self.execution.goals), "goal_set_sha256": self.execution.goal_set_sha256,
            "matched_budget": self.execution.matched_budget,
            "max_model_calls_total": TOTAL_GOALS * capacity.LIMITS.max_model_calls,
            "primary_capacity_plan_sha256": execution["plan_sha256"],
            "execution_contract": contract, "execution_binding": binding,
            "training_origins": {
                "catalog": self.catalog_origin, "scaled": self.scaled_origin,
                "corrected": {"preparation_manifest_sha256": self.execution.authority.preparation_manifest_sha256,
                              "authority_profile": AUTHORITY_PRIMITIVE_PROFILE,
                              "endpoint": "single-completed-fresh-base-one-epoch-final-adapter"},
            },
            "preserved_origin_receipts": {"catalog": self.catalog.sha256, "scaled": self.scaled.sha256},
            "source_files": sources, "source_coverage": capacity.SOURCE_COVERAGE,
            "max_report_bytes": comparison.MAX_REPORT_BYTES,
            "max_goal_evidence_bytes": shared.MAX_GOAL_EVIDENCE_BYTES,
            "offline_replay_limits": capacity.REPLAY_LIMITS.to_dict(),
            "per_goal_time_limit": None,
            "interruption_policy": "preserve-inflight-as-unknown; no automatic retry or old checkpoint merge",
        }
        return {**record, "plan_sha256": _digest(record)}


def build_corrective_plan(preparation_directory: Path, *, catalog: OriginReceipt,
                          scaled: OriginReceipt, trained_adapter: Path | None = None,
                          repository_root: Path = ROOT) -> CorrectivePlan:
    from hydra_training_v5.peano_hydra.corrective_source import CORRECTIVE_SOURCE_SCHEMA

    old = _preserved(catalog, "catalog")
    previous_scaled = _preserved(scaled, "scaled")
    raw = shared._read_regular(preparation_directory / "manifest.json", maximum=shared.MAX_MANIFEST_BYTES,
                               description="corrective preparation")
    manifest = shared._json_object(raw, description="corrective preparation")
    _require(type(manifest.get("source")) is dict and manifest["source"].get("schema") == CORRECTIVE_SOURCE_SCHEMA,
             "corrective experiment requires its newly admitted mixed source")
    execution = capacity.build_capacity_plan(preparation_directory, trained_adapter=trained_adapter,
                                            repository_root=repository_root,
                                            authority_profile=AUTHORITY_PRIMITIVE_PROFILE)
    _require(type(execution) is capacity.CapacityPlan and execution.authority_profile == AUTHORITY_PRIMITIVE_PROFILE,
             "corrective execution requires the independently regenerated V4 preparation")
    _require(_same(execution.goals, comparison.comparison_goals()[:GOAL_COUNT]), "corrective PRIMARY32 goals changed")
    for origin in (old.origin, previous_scaled.origin):
        _require(_same(origin["model"], execution.model)
                 and origin["epoch_sha256"] == execution.epoch.epoch_sha256
                 and origin["edition_identity_sha256"] == execution.epoch.edition_identity_sha256
                 and origin["theorem_dag_sha256"] == execution.epoch.theorem_dag_sha256
                 and origin["reviewed_definition_dag_sha256"] == execution.epoch.reviewed_definition_dag_sha256,
                 "corrective comparison origins must share the exact base and frozen mathematical epoch")
    _require(_same(old.origin["artifacts"]["tokenizer"], previous_scaled.origin["artifacts"]["tokenizer"]),
             "preserved origins use different tokenizer artifacts")
    if execution.authority.trained_adapter is not None:
        current, _, _ = comparison._origin(execution.authority, previous=False)
        _require(_same(current["artifacts"]["tokenizer"], old.origin["artifacts"]["tokenizer"]),
                 "corrective adapter uses different tokenizer artifacts")
    return CorrectivePlan(execution, catalog, scaled, _canonical(old.origin).decode(),
                          _canonical(previous_scaled.origin).decode(), _canonical(_sources()).decode())


def _refresh(plan: CorrectivePlan):
    _require(type(plan) is CorrectivePlan, "corrective evaluation requires its exact independently built plan")
    adapter = plan.execution.authority.trained_adapter
    fresh = build_corrective_plan(plan.execution.authority.preparation_directory,
                                  catalog=plan.catalog, scaled=plan.scaled,
                                  trained_adapter=None if adapter is None else Path(adapter["manifest_path"]))
    _require(_same(fresh.to_dict(), plan.to_dict())
             and _same(fresh.execution.authority.trained_adapter, adapter),
             "corrective preparation, execution or origin changed after planning")


def _origins(plan: CorrectivePlan):
    catalog = _preserved(plan.catalog, "catalog")
    scaled = _preserved(plan.scaled, "scaled")
    _require(_same(catalog.origin, plan.catalog_origin) and _same(scaled.origin, plan.scaled_origin),
             "preserved origins changed after planning")
    corrected, new_directory, new_tokenizer = comparison._origin(plan.execution.authority, previous=False)
    _require(_same(corrected["artifacts"]["tokenizer"], catalog.origin["artifacts"]["tokenizer"])
             and _same(scaled.origin["artifacts"]["tokenizer"], catalog.origin["artifacts"]["tokenizer"]),
             "corrective comparison tokenizer identity differs")
    base = {"kind": "pinned-pretrained-base", "model": plan.model, "adapter_attached": False,
            "training_authority_profile": None, "research_claim_eligible": False}
    base["origin_sha256"] = _digest(base)
    return {"base": base, "catalog": catalog.origin, "scaled": scaled.origin, "corrected": corrected}, {
        "catalog": catalog.adapter_directory, "scaled": scaled.adapter_directory, "corrected": new_directory,
    }, new_tokenizer


def _runtime(runtime):
    _keys(runtime, {"torch_version", "transformers_version", "peft_version", "visible_cuda_devices", "cuda_device",
                    "dtype", "attention", "local_files_only", "model_loading"}, "corrective runtime")
    _require(all(type(runtime[key]) is str and 1 <= len(runtime[key]) <= 256 for key in (
        "torch_version", "transformers_version", "peft_version", "cuda_device")), "invalid corrective runtime text")
    _require(type(runtime["visible_cuda_devices"]) is int and runtime["visible_cuda_devices"] == 1
             and runtime["dtype"] == "bfloat16" and runtime["attention"] == "sdpa"
             and runtime["local_files_only"] is True and runtime["model_loading"] == LOADING,
             "corrective runtime changed its single-GPU sequential contract")


class PrimaryCheckpointStore(cp.CheckpointStore):
    """The reviewed durable store with a fixed, non-interchangeable 128-row panel."""

    total_goals = TOTAL_GOALS
    goals_per_role = GOAL_COUNT
    head_schema = HEAD_SCHEMA
    verify_schema = PREFIX_SCHEMA
    claim = CLAIM

    def _goal_inventory(self):
        _require(type(self.plan) is CorrectivePlan, "primary checkpoint requires a corrective plan")
        return self.plan.execution.goals

    def _make_header(self, runtime):
        _runtime(runtime)
        return cp._sign({"schema": HEADER_SCHEMA, "plan": self.plan.to_dict(), "training_origins": self.origins,
                         "provider_runtime": runtime, "order": "role-primary-goal", "goal_records": TOTAL_GOALS,
                         "research_claim_eligible": False, "historical_gpu_inference_attested": False}, "header_sha256")

    def _goal_binding(self, index):
        _integer(index, "corrective checkpoint ordinal", TOTAL_GOALS - 1)
        goal = self.goals[index % GOAL_COUNT]
        return {"ordinal": index + 1, "role": ROLES[index // GOAL_COUNT], "cohort": "primary",
                "goal": goal["name"], "goal_sha256": _digest(goal),
                "source_sha256": hashlib.sha256(goal["source"].encode()).hexdigest(),
                "statement_sha256": goal["statement_sha256"]}

    def _make_record(self, previous, binding, row):
        return cp._sign({"schema": ROW_SCHEMA, "header_sha256": self.header["header_sha256"],
                         "previous_sha256": previous, **binding, "row": row, "row_sha256": _digest(row),
                         "proposal_records_sha256": _digest(row["evidence"]["proposal_records"]),
                         "evidence_sha256": row["evidence_sha256"], "commands_sha256": row["commands_sha256"]},
                        "record_sha256")

    def _contexts(self):
        self.contexts = {(role, "primary"): (self.plan.execution, comparison._provider(
            self.plan, role, self.header["provider_runtime"], self.origins)) for role in ROLES}


def _metrics(plan, lanes):
    rows = {role: lanes[role]["primary"]["goals"] for role in ROLES}
    metrics = {role: comparison._panel_metrics(plan.execution.goals, rows[role]) for role in ROLES}
    paired = {}
    for reference in ROLES[:-1]:
        pairs = list(zip(rows[reference], rows["corrected"], strict=True))
        paired["corrected_vs_" + reference] = {
            "both_proved": sum(a["kernel_checked"] and b["kernel_checked"] for a, b in pairs),
            "corrected_only": [goal["name"] for goal, (a, b) in zip(plan.execution.goals, pairs, strict=True)
                               if not a["kernel_checked"] and b["kernel_checked"]],
            "reference_only": [goal["name"] for goal, (a, b) in zip(plan.execution.goals, pairs, strict=True)
                               if a["kernel_checked"] and not b["kernel_checked"]],
            "neither_proved": sum(not a["kernel_checked"] and not b["kernel_checked"] for a, b in pairs),
            "kernel_checked_proof_delta": metrics["corrected"]["kernel_checked_proofs"] - metrics[reference]["kernel_checked_proofs"],
        }
    return {"primary": {"roles": metrics, "paired": paired}}


def validate_result(plan: CorrectivePlan, result: dict, *, replay: bool, origins: dict | None = None):
    _require(type(plan) is CorrectivePlan and type(replay) is bool, "invalid corrective verification input")
    _require(not replay or not {"torch", "transformers", "peft"} & set(sys.modules),
             "independent proof verification must precede model imports")
    _require(len(_canonical(result)) <= comparison.MAX_REPORT_BYTES, "corrective result exceeds byte bound")
    _keys(result, {"schema", "status", "plan", "training_origins", "provider_runtime", "lanes", "metrics",
                   "claim_boundary", "research_claim_eligible", "sealed_benchmark", "independent_discoveries",
                   "evaluation_sha256"}, "corrective result")
    capacity._signed(result, "evaluation_sha256")
    if origins is None or replay:
        origins, _, _ = _origins(plan)
    _require(result["schema"] == RESULT_SCHEMA and result["status"] == "executed"
             and _same(result["plan"], plan.to_dict()) and _same(result["training_origins"], origins)
             and result["claim_boundary"] == CLAIM and all(result[key] is False for key in (
                 "research_claim_eligible", "sealed_benchmark", "independent_discoveries")),
             "corrective result changed its complete plan, origins or claim")
    _runtime(result["provider_runtime"])
    _keys(result["lanes"], set(ROLES), "corrective model roles")
    checked = []
    for role in ROLES:
        _keys(result["lanes"][role], {"primary"}, "corrective primary panel")
        checked.extend(comparison._validate_lane(plan, role, "primary", result["lanes"][role]["primary"],
                                                 result["provider_runtime"], origins, replay=replay))
    _require(_same(result["metrics"], _metrics(plan, result["lanes"])), "corrective paired metrics differ")
    return {"schema": VERIFY_SCHEMA, "status": "passed", "plan_sha256": plan.to_dict()["plan_sha256"],
            "evaluation_sha256": result["evaluation_sha256"], "metrics": result["metrics"],
            "proof_replay_performed": replay, "independently_replayed_proofs": checked if replay else [],
            "historical_gpu_inference_attested": False, "model_outputs_regenerated": False,
            "research_claim_eligible": False, "claim_boundary": CLAIM}


def execute_corrective_comparison(plan: CorrectivePlan, *, checkpoint_directory: Path,
                                 progress: cp.Progress | None = None,
                                 stop_after_seconds: float | None = None,
                                 stop_requested: Callable[[], bool] | None = None):
    """Explicit fresh inference only; no resume, retry or checkpoint conversion.

    Soft deadlines are checked between goals. An interrupted in-flight goal
    remains unknown, and cannot be automatically retried under a fresh budget.
    """
    if stop_after_seconds is not None:
        _require(type(stop_after_seconds) in (int, float) and math.isfinite(stop_after_seconds)
                 and 0 < stop_after_seconds <= 1800, "corrective evaluation soft stop exceeds its reservation")
    _require(stop_requested is None or callable(stop_requested), "invalid stop hook")
    progress = progress or cp.Progress()
    progress.emit("validation-start", profile=PLAN_SCHEMA)
    _refresh(plan)
    origins, adapters, tokenizer_directory = _origins(plan)
    # Check destination before importing frameworks or loading weights. The
    # store repeats this with anchored no-replace creation before inference.
    cp.check_fresh_output(checkpoint_directory)
    progress.emit("validation-complete", plan_sha256=plan.to_dict()["plan_sha256"])
    reason = "signal" if stop_requested is not None and stop_requested() else (
        "soft_deadline" if stop_after_seconds is not None
        and time.monotonic() - progress.started >= stop_after_seconds else None)
    if reason is not None:
        # The CLI's clock includes setup. Do not load weights merely to learn
        # that validation has used up the soft reservation.
        raise cp.CheckpointPaused({"schema": PREFIX_SCHEMA, "status": "paused-before-inference",
                                   "pause_reason": reason, "completed_goal_records": 0,
                                   "total_goal_records": TOTAL_GOALS, "checkpoint_created": False,
                                   "model_loaded": False, "research_claim_eligible": False})
    torch, transformers, peft = shared._model_runtime()
    runtime = {"torch_version": str(torch.__version__), "transformers_version": str(transformers.__version__),
               "peft_version": str(peft.__version__), "visible_cuda_devices": 1,
               "cuda_device": torch.cuda.get_device_name(0), "dtype": "bfloat16", "attention": "sdpa",
               "local_files_only": True, "model_loading": LOADING}
    with PrimaryCheckpointStore(checkpoint_directory, plan, origins, runtime=runtime, progress=progress) as store:
        shared._reset_seed(torch, transformers, capacity.SEED)
        tokenizer = transformers.AutoTokenizer.from_pretrained(
            str(tokenizer_directory), trust_remote_code=False, use_fast=True, local_files_only=True)
        if tokenizer.pad_token_id is None:
            _require(tokenizer.eos_token_id is not None, "corrective tokenizer lacks EOS/padding")
            tokenizer.pad_token_id = tokenizer.eos_token_id

        def stop_at_boundary():
            reason = "signal" if stop_requested is not None and stop_requested() else (
                "soft_deadline" if stop_after_seconds is not None
                and time.monotonic() - progress.started >= stop_after_seconds else None)
            if reason is not None and len(store.rows) < TOTAL_GOALS:
                store.assert_unchanged()
                receipt = {**store.receipt(status="paused"), "pause_reason": reason}
                progress.emit("paused", completed=len(store.rows), total=TOTAL_GOALS, reason=reason)
                raise cp.CheckpointPaused(receipt)

        lanes = {}
        for role in ROLES:
            model = None
            try:
                stop_at_boundary()
                fresh, _, _ = _origins(plan)
                _require(_same(fresh, origins), "origin bytes changed before model loading")
                shared._reset_seed(torch, transformers, capacity.SEED)
                progress.emit("model-loading-start", role=role, completed=len(store.rows), total=TOTAL_GOALS)
                model = shared._load_base_model(torch, transformers, plan.model)
                if role != "base":
                    model = peft.PeftModel.from_pretrained(model, str(adapters[role]), is_trainable=False)
                model.to("cuda:0")
                model.eval()
                progress.emit("model-loading-complete", role=role, completed=len(store.rows), total=TOTAL_GOALS)
                goal_started = [0.0, 0.0]

                def begin(goal):
                    stop_at_boundary()
                    store.begin(role, "primary", goal)
                    goal_started[:] = [time.monotonic(), time.process_time()]
                    progress.emit("goal-start", role=role, goal=goal["name"], completed=len(store.rows), total=TOTAL_GOALS)

                def committed(row):
                    store.append(row)
                    progress.emit("goal-committed", role=role, goal=row["goal"], completed=len(store.rows),
                                  total=TOTAL_GOALS, status=row["status"], kernel_checked=row["kernel_checked"],
                                  model_generate_calls=row["model_generate_calls"],
                                  goal_wall_seconds=round(time.monotonic() - goal_started[0], 6),
                                  goal_cpu_seconds=round(time.process_time() - goal_started[1], 6),
                                  checkpoint_head_sha256=store.head["head_sha256"])

                lane = shared._run_model_lane(plan.execution, model=model, tokenizer=tokenizer,
                                              lane="pretrained" if role == "base" else "trained",
                                              provider=comparison._provider(plan, role, runtime, origins),
                                              on_goal_start=begin, on_goal=committed)
                start = ROLES.index(role) * GOAL_COUNT
                _require(_same(lane["goals"], store.rows[start:start + GOAL_COUNT]), "live and checkpoint rows differ")
                lanes[role] = {"primary": lane}
                progress.emit("primary-role-complete", role=role, completed=len(store.rows), total=TOTAL_GOALS,
                              kernel_checked_proofs=lane["kernel_checked_proofs"])
            finally:
                del model
                from hydra_training_v5.peano_policy.authority_runtime import clear_authority_runtime_cache

                clear_authority_runtime_cache()
                shared._release_gpu(torch)
                progress.emit("model-unloaded", role=role)
        _require(len(store.rows) == TOTAL_GOALS and store.head["inflight"] is None,
                 "partial corrective evidence cannot publish a complete comparison")
        _refresh(plan)
        fresh, _, _ = _origins(plan)
        _require(_same(fresh, origins), "origin bytes changed during evaluation")
        store.assert_unchanged()
        result = {"schema": RESULT_SCHEMA, "status": "executed", "plan": plan.to_dict(),
                  "training_origins": origins, "provider_runtime": runtime, "lanes": lanes,
                  "metrics": _metrics(plan, lanes), "claim_boundary": CLAIM,
                  "research_claim_eligible": False, "sealed_benchmark": False, "independent_discoveries": False}
        result["evaluation_sha256"] = _digest(result)
        validate_result(plan, result, replay=False, origins=origins)
        progress.emit("evaluation-complete", completed=TOTAL_GOALS, total=TOTAL_GOALS,
                      evaluation_sha256=result["evaluation_sha256"])
        return result


