"""Constructive weighted vertical identity for relational Choose.

The candidate below proves the Pascal vertical identity directly, without a
factorial representation or cancellation.  Every ``Choose`` occurrence is
expanded into ordinary first-order Peano arithmetic before parsing.  This
module creates no trusted primitive, authority enrollment, or checked-use
grant.
"""

from __future__ import annotations

from typing import Any, Callable

from peano_lab.library.bertrand_choose_foundation_candidate import (
    _choose_relation_term,
)


CHOOSE_WEIGHTED_VERTICAL = "choose_weighted_vertical"


def make_bertrand_choose_weighted_vertical_candidate_theorems(
    spec: Callable[..., Any],
) -> tuple[Any, ...]:
    """Build the isolated constructive weighted-vertical candidate."""

    variables = ("n", "k", "j", "x", "y")
    lower = _choose_relation_term(
        "n",
        "k",
        "x",
        tag="bcwv_lower",
        variables=variables,
    )
    upper = _choose_relation_term(
        "S n",
        "k",
        "y",
        tag="bcwv_upper",
        variables=variables,
    )
    previous_left = _choose_relation_term(
        "n",
        "k",
        "a",
        tag="bcwv_previous_left",
        variables=variables + ("a",),
    )
    previous_right = _choose_relation_term(
        "n",
        "S k",
        "b",
        tag="bcwv_previous_right",
        variables=variables + ("b",),
    )
    diagonal_successor_left = _choose_relation_term(
        "S n",
        "k",
        "b",
        tag="bcwv_successor_left",
        variables=variables + ("b",),
    )
    interior_successor_left = _choose_relation_term(
        "S n",
        "k",
        "c",
        tag="bcwv_successor_left",
        variables=variables + ("c",),
    )

    script = (
        # Induct on the row first so IH remains generalized over the column,
        # complement, and both relational values.
        "induction n",
        # Row zero, column zero.  The complement equation itself forces j=0.
        "induction k",
        "intro j",
        "intro x",
        "intro y",
        "intro hsum",
        "intro hlower",
        "intro hupper",
        "have hj : j = 0",
        "trans 0 + j",
        "symm",
        "apply zero_add",
        "exact hsum",
        "have hx : x = 1",
        "specialize choose_zero 0",
        "specialize choose_zero x",
        "apply choose_zero",
        "exact hlower",
        "have hy : y = 1",
        "specialize choose_zero (S 0)",
        "specialize choose_zero y",
        "apply choose_zero",
        "exact hupper",
        "rewrite hj",
        "trans S 0 * 1",
        "congr",
        "refl",
        "exact hy",
        "congr",
        "refl",
        "symm",
        "exact hx",
        # No successor column can have a complement in row zero.
        "intro j",
        "intro x",
        "intro y",
        "intro hsum",
        "intro hlower",
        "intro hupper",
        "specialize add_succ_left k",
        "specialize add_succ_left j",
        "rewrite add_succ_left at hsum",
        "exfalso",
        "apply PA1",
        "exact hsum",
        # Every successor row has value one in column zero.
        "induction k",
        "intro j",
        "intro x",
        "intro y",
        "intro hsum",
        "intro hlower",
        "intro hupper",
        "have hj : j = S n",
        "trans 0 + j",
        "symm",
        "apply zero_add",
        "exact hsum",
        "have hx : x = 1",
        "specialize choose_zero (S n)",
        "specialize choose_zero x",
        "apply choose_zero",
        "exact hlower",
        "have hy : y = 1",
        "specialize choose_zero (S (S n))",
        "specialize choose_zero y",
        "apply choose_zero",
        "exact hupper",
        "rewrite hj",
        "trans S (S n) * 1",
        "congr",
        "refl",
        "exact hy",
        "congr",
        "refl",
        "symm",
        "exact hx",
        # For a positive column, split the complement into its diagonal and
        # interior cases.
        "intro j",
        "intro x",
        "intro y",
        "intro hsum",
        "intro hlower",
        "intro hupper",
        "specialize zero_or_succ j",
        "cases zero_or_succ",
        # Diagonal boundary j=0.  Obtain the two cells immediately to the
        # left in isolated subgoals, preserving inferable elimination sources.
        f"have ha_exists : exists a. ({previous_left})",
        "specialize choose_exists n",
        "specialize choose_exists k",
        "exact choose_exists",
        "cases ha_exists",
        f"have hb_exists : exists b. ({diagonal_successor_left})",
        "specialize choose_exists (S n)",
        "specialize choose_exists k",
        "exact choose_exists",
        "cases hb_exists",
        "rewrite zero_or_succ_left at hsum",
        "rewrite PA3 at hsum",
        "have hk : k = n",
        "apply PA2",
        "exact hsum",
        "have hprevious_sum : k + 0 = n",
        "trans k",
        "apply PA3",
        "exact hk",
        "have ha_one : x1 = 1",
        "specialize choose_self_of_eq n",
        "specialize choose_self_of_eq k",
        "specialize choose_self_of_eq x1",
        "apply choose_self_of_eq",
        "exact hk",
        "exact ha_exists_witness",
        "have hx_one : x = 1",
        "specialize choose_self_of_eq (S n)",
        "specialize choose_self_of_eq (S k)",
        "specialize choose_self_of_eq x",
        "apply choose_self_of_eq",
        "exact hsum",
        "exact hlower",
        "have hweighted : S 0 * x2 = S n * x1",
        "specialize IH k",
        "specialize IH 0",
        "specialize IH x1",
        "specialize IH x2",
        "apply IH",
        "exact hprevious_sum",
        "exact ha_exists_witness",
        "exact hb_exists_witness",
        "have hy_sum : y = x2 + x",
        "specialize choose_succ_succ (S n)",
        "specialize choose_succ_succ k",
        "specialize choose_succ_succ x2",
        "specialize choose_succ_succ x",
        "specialize choose_succ_succ y",
        "apply choose_succ_succ",
        "exact hb_exists_witness",
        "exact hlower",
        "exact hupper",
        "have hsame_one : x1 = x",
        "trans 1",
        "exact ha_one",
        "symm",
        "exact hx_one",
        "have hone_scale : S 0 * x = x",
        "trans S 0 * 1",
        "congr",
        "refl",
        "exact hx_one",
        "trans 1",
        "trans S 0 * 0 + S 0",
        "apply PA6",
        "rewrite PA5",
        "apply zero_add",
        "symm",
        "exact hx_one",
        "rewrite zero_or_succ_left",
        "trans S 0 * (x2 + x)",
        "congr",
        "refl",
        "exact hy_sum",
        "trans S 0 * x2 + S 0 * x",
        "apply mul_add",
        "trans S n * x1 + S 0 * x",
        "congr",
        "exact hweighted",
        "refl",
        "trans S n * x + x",
        "congr",
        "congr",
        "refl",
        "exact hsame_one",
        "exact hone_scale",
        "specialize mul_succ_left (S n)",
        "specialize mul_succ_left x",
        "symm",
        "exact mul_succ_left",
        # Interior j=S J.  Use two outer IH instances and two Pascal steps.
        "cases zero_or_succ_right",
        f"have ha_exists : exists a. ({previous_left})",
        "specialize choose_exists n",
        "specialize choose_exists k",
        "exact choose_exists",
        "cases ha_exists",
        f"have hb_exists : exists b. ({previous_right})",
        "specialize choose_exists n",
        "specialize choose_exists (S k)",
        "exact choose_exists",
        "cases hb_exists",
        f"have hc_exists : exists c. ({interior_successor_left})",
        "specialize choose_exists (S n)",
        "specialize choose_exists k",
        "exact choose_exists",
        "cases hc_exists",
        "rewrite zero_or_succ_right_witness at hsum",
        "have hsecond_complement : S k + x1 = n",
        "apply PA2",
        "trans S k + S x1",
        "symm",
        "apply PA4",
        "exact hsum",
        "have hfirst_complement : k + S x1 = n",
        "trans S (k + x1)",
        "apply PA4",
        "trans S k + x1",
        "symm",
        "apply add_succ_left",
        "exact hsecond_complement",
        "have hx_sum : x = x2 + x3",
        "specialize choose_succ_succ n",
        "specialize choose_succ_succ k",
        "specialize choose_succ_succ x2",
        "specialize choose_succ_succ x3",
        "specialize choose_succ_succ x",
        "apply choose_succ_succ",
        "exact ha_exists_witness",
        "exact hb_exists_witness",
        "exact hlower",
        "have hy_sum : y = x4 + x",
        "specialize choose_succ_succ (S n)",
        "specialize choose_succ_succ k",
        "specialize choose_succ_succ x4",
        "specialize choose_succ_succ x",
        "specialize choose_succ_succ y",
        "apply choose_succ_succ",
        "exact hc_exists_witness",
        "exact hlower",
        "exact hupper",
        "have hfirst_weight : S (S x1) * x4 = S n * x2",
        "specialize IH k",
        "specialize IH (S x1)",
        "specialize IH x2",
        "specialize IH x4",
        "apply IH",
        "exact hfirst_complement",
        "exact ha_exists_witness",
        "exact hc_exists_witness",
        "have hsecond_weight : S x1 * x = S n * x3",
        "specialize IH (S k)",
        "specialize IH x1",
        "specialize IH x3",
        "specialize IH x",
        "apply IH",
        "exact hsecond_complement",
        "exact hb_exists_witness",
        "exact hlower",
        "rewrite zero_or_succ_right_witness",
        "trans S (S x1) * (x4 + x)",
        "congr",
        "refl",
        "exact hy_sum",
        "trans S (S x1) * x4 + S (S x1) * x",
        "apply mul_add",
        "trans S n * x2 + (S x1 * x + x)",
        "congr",
        "exact hfirst_weight",
        "specialize mul_succ_left (S x1)",
        "specialize mul_succ_left x",
        "apply mul_succ_left",
        "trans S n * x2 + (S n * x3 + x)",
        "congr",
        "refl",
        "congr",
        "exact hsecond_weight",
        "refl",
        "trans (S n * x2 + S n * x3) + x",
        "specialize add_assoc (S n * x2)",
        "specialize add_assoc (S n * x3)",
        "specialize add_assoc x",
        "symm",
        "apply add_assoc",
        "trans S n * (x2 + x3) + x",
        "congr",
        "specialize mul_add (S n)",
        "specialize mul_add x2",
        "specialize mul_add x3",
        "symm",
        "apply mul_add",
        "refl",
        "trans S n * x + x",
        "congr",
        "congr",
        "refl",
        "symm",
        "exact hx_sum",
        "refl",
        "specialize mul_succ_left (S n)",
        "specialize mul_succ_left x",
        "symm",
        "exact mul_succ_left",
    )

    return (
        spec(
            CHOOSE_WEIGHTED_VERTICAL,
            "forall n k j x y. k + j = n -> "
            f"({lower}) -> ({upper}) -> S j * y = S n * x",
            (
                "zero_or_succ",
                "zero_add",
                "add_succ_left",
                "add_assoc",
                "mul_succ_left",
                "mul_add",
                "choose_exists",
                "choose_zero",
                "choose_self_of_eq",
                "choose_succ_succ",
            ),
            script,
            "Adjacent rows satisfy the constructive weighted vertical identity.",
        ),
    )


__all__ = ["make_bertrand_choose_weighted_vertical_candidate_theorems"]
