# The public valuation helper intentionally accepts identifiers only.  This
# private compiler mirrors its reviewed expansion for the product term ``a*b``.
def _power_valuation_terms(base: str, value: str, exponent: str, *, tag: str) -> str:
    candidate = f"bpd_candidate_{tag}"
    exponent_bound = _le_terms(exponent, value, tag=f"{tag}_selected_bound")
    exponent_divides = _power_divides_terms(
        base, exponent, value, tag=f"{tag}_selected"
    )
    candidate_bound = _le_terms(candidate, value, tag=f"{tag}_candidate_bound")
    candidate_divides = _power_divides_terms(
        base, candidate, value, tag=f"{tag}_candidate"
    )
    candidate_below = _le_terms(candidate, exponent, tag=f"{tag}_maximal")
    return (
        f"(({exponent_bound}) /\\ ({exponent_divides})) /\\ "
        f"forall {candidate}. ({candidate_bound}) -> "
        f"({candidate_divides}) -> ({candidate_below})"
    )


