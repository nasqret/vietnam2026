"""Reusable prime-power divisibility algebra for Bertrand valuations.

``PowDiv(p,e,a)`` remains a fully expanded relation: a beta-coded relational
power of ``p`` at exponent ``e`` has an ordinary multiplicative witness into
``a``.  This isolated tranche supplies the antitone exponent law, composition
under multiplication, and exact-cofactor cancellation needed for valuation
addition.  No surface predicate reaches the parser or kernel.

The factory is intentionally unregistered.  Admission, edition enrollment,
and publication are separate reviewed operations.
"""

