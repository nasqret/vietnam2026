def _le_terms(left: str, right: str, *, tag: str) -> str:
    return f"exists bpd_gap_{tag}. bpd_gap_{tag} + ({left}) = ({right})"


def _divides_terms(divisor: str, value: str, *, tag: str) -> str:
    return f"exists bpd_factor_{tag}. {value} = ({divisor}) * bpd_factor_{tag}"


def _exact_cofactor(
    base: str,
    exponent: str,
    value: str,
    *,
    tag: str,
) -> str:
    result = f"bpd_result_{tag}"
    cofactor = f"bpd_cofactor_{tag}"
    power = power_relation(base, exponent, result, tag=f"{tag}_power")
    cofactor_nonzero = f"~({cofactor} = 0)"
    cofactor_nondivisible = f"~({_divides_terms(base, cofactor, tag=f'{tag}_prime')})"
    return (
        f"exists {result} {cofactor}. (({power}) /\\ "
        f"(({value} = {result} * {cofactor}) /\\ "
        f"(({cofactor_nonzero}) /\\ ({cofactor_nondivisible}))))"
    )


