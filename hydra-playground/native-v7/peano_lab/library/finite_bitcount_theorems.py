"""Checked theorem data for beta-coded zero/one counts.

This module is an untrusted authoring layer.  ``AllBits`` and ``BitCount``
are expanded by :mod:`finite_fold_surface` into ordinary first-order Peano
formulas; the independent kernel remains the authority for every certificate.
"""

from __future__ import annotations

from typing import Any, Callable

from .finite_fold_surface import (
    BIT_COUNT_BOUNDED,
    BIT_COUNT_EXISTS,
    BIT_COUNT_FUNCTIONAL,
    all_bits,
    beta_at,
    bit_count,
    sum_relation,
)


def make_finite_bitcount_theorems(spec: Callable[..., Any]) -> tuple[Any, ...]:
    """Build the dependency-ordered ``AllBits``/``BitCount`` tranche."""

    empty_bits = all_bits("b", "c", "l", tag="empty")
    successor_bits = all_bits("b", "c", "sl", tag="successor")
    prefix_bits = all_bits("b", "c", "l", tag="prefix")
    last_bit = beta_at("b", "c", "l", "a", tag="last")
    zero_count = bit_count("b", "c", "l", "n", tag="zero")
    successor_count = bit_count("b", "c", "sl", "n", tag="successor")
    prefix_count = bit_count("b", "c", "l", "r", tag="prefix")
    sum_last = beta_at("b", "c", "l", "a", tag="sum_last")
    sum_prefix = sum_relation("b", "c", "l", "r", tag="sum_prefix")
    sum_successor_decomposition = (
        f"exists a r. ({sum_last}) /\\ (({sum_prefix}) /\\ n = r + a)"
    )
    successor_decomposition = (
        f"exists a r. ({last_bit}) /\\ (({prefix_count}) /\\ "
        f"((a = 0 \\/ a = 1) /\\ n = r + a))"
    )

    return (
        spec(
            "all_bits_zero",
            f"forall b c l. l = 0 -> ({empty_bits})",
            ("add_eq_zero_right", "succ_ne_zero"),
            (
                "intro b",
                "intro c",
                "intro l",
                "intro hl",
                "intro i",
                "intro hi",
                "rewrite hl at hi",
                "exfalso",
                "cases hi",
                "have hsi : S i = 0",
                "specialize add_eq_zero_right x",
                "specialize add_eq_zero_right (S i)",
                "apply add_eq_zero_right",
                "exact hi_witness",
                "specialize succ_ne_zero i",
                "apply succ_ne_zero",
                "exact hsi",
            ),
            "The empty decoded prefix consists only of bits, vacuously.",
        ),
        spec(
            "all_bits_prefix_succ",
            f"forall b c l sl. sl = S l -> ({successor_bits}) -> "
            f"({prefix_bits})",
            ("le_succ",),
            (
                "intro b",
                "intro c",
                "intro l",
                "intro sl",
                "intro hsl",
                "intro hbits",
                "rewrite hsl at hbits",
                "intro i",
                "intro hi",
                "specialize hbits i",
                "apply hbits",
                "specialize le_succ (S i)",
                "specialize le_succ l",
                "apply le_succ",
                "exact hi",
            ),
            "Dropping the final entry preserves the all-bits invariant.",
        ),
        spec(
            "all_bits_last_succ",
            f"forall b c l sl. sl = S l -> ({successor_bits}) -> exists a. "
            f"(({last_bit}) /\\ (a = 0 \\/ a = 1))",
            ("le_refl",),
            (
                "intro b",
                "intro c",
                "intro l",
                "intro sl",
                "intro hsl",
                "intro hbits",
                "rewrite hsl at hbits",
                "specialize hbits l",
                "apply hbits",
                "specialize le_refl (S l)",
                "exact le_refl",
            ),
            "The final entry of a nonempty all-bits prefix is zero or one.",
        ),
        spec(
            "bit_count_exists",
            BIT_COUNT_EXISTS,
            ("beta_sum_exists",),
            (
                "intro b",
                "intro c",
                "intro l",
                "intro hbits",
                "specialize beta_sum_exists b",
                "specialize beta_sum_exists c",
                "specialize beta_sum_exists l",
                "cases beta_sum_exists",
                "exists x",
                "split",
                "exact beta_sum_exists_witness",
                "exact hbits",
            ),
            "Every all-bits prefix has a relational count of its ones.",
        ),
        spec(
            "bit_count_functional",
            BIT_COUNT_FUNCTIONAL,
            ("beta_sum_functional",),
            (
                "intro b",
                "intro c",
                "intro l",
                "intro n",
                "intro m",
                "intro hn",
                "intro hm",
                "cases hn",
                "cases hm",
                "specialize beta_sum_functional b",
                "specialize beta_sum_functional c",
                "specialize beta_sum_functional l",
                "specialize beta_sum_functional n",
                "specialize beta_sum_functional m",
                "apply beta_sum_functional",
                "exact hn_left",
                "exact hm_left",
            ),
            "The relational count of a fixed all-bits prefix is unique.",
        ),
        spec(
            "bit_count_zero",
            f"forall b c l n. l = 0 -> ({zero_count}) -> n = 0",
            ("beta_sum_zero",),
            (
                "intro b",
                "intro c",
                "intro l",
                "intro n",
                "intro hl",
                "intro hcount",
                "rewrite hl at hcount",
                "rewrite hl at hcount",
                "rewrite hl at hcount",
                "cases hcount",
                "specialize beta_sum_zero b",
                "specialize beta_sum_zero c",
                "specialize beta_sum_zero n",
                "apply beta_sum_zero",
                "exact hcount_left",
            ),
            "An empty bit prefix contains zero ones.",
        ),
        spec(
            "bit_count_succ_decompose",
            f"forall b c l sl n. sl = S l -> ({successor_count}) -> "
            f"{successor_decomposition}",
            (
                "beta_sum_succ_decompose",
                "all_bits_prefix_succ",
                "all_bits_last_succ",
                "beta_at_unique",
            ),
            (
                "intro b",
                "intro c",
                "intro l",
                "intro sl",
                "intro n",
                "intro hsl",
                "intro hcount",
                "rewrite hsl at hcount",
                "rewrite hsl at hcount",
                "rewrite hsl at hcount",
                "rewrite hsl at hcount",
                "cases hcount",
                f"have hsum : {sum_successor_decomposition}",
                "specialize beta_sum_succ_decompose b",
                "specialize beta_sum_succ_decompose c",
                "specialize beta_sum_succ_decompose l",
                "specialize beta_sum_succ_decompose n",
                "apply beta_sum_succ_decompose",
                "exact hcount_left",
                "cases hsum",
                "cases hsum_witness",
                "cases hsum_witness_witness",
                "cases hsum_witness_witness_right",
                "have hlast : exists a. "
                f"(({beta_at('b', 'c', 'l', 'a', tag='bits_last')}) /\\ "
                "(a = 0 \\/ a = 1))",
                "specialize all_bits_last_succ b",
                "specialize all_bits_last_succ c",
                "specialize all_bits_last_succ l",
                "specialize all_bits_last_succ (S l)",
                "apply all_bits_last_succ",
                "refl",
                "exact hcount_right",
                "cases hlast",
                "cases hlast_witness",
                "have ha : x = x2",
                "specialize beta_at_unique b",
                "specialize beta_at_unique c",
                "specialize beta_at_unique l",
                "specialize beta_at_unique x",
                "specialize beta_at_unique x2",
                "apply beta_at_unique",
                "exact hsum_witness_witness_left",
                "exact hlast_witness_left",
                f"have hprefix : {all_bits('b', 'c', 'l', tag='kept_prefix')}",
                "specialize all_bits_prefix_succ b",
                "specialize all_bits_prefix_succ c",
                "specialize all_bits_prefix_succ l",
                "specialize all_bits_prefix_succ (S l)",
                "apply all_bits_prefix_succ",
                "refl",
                "exact hcount_right",
                "exists x",
                "exists x1",
                "split",
                "exact hsum_witness_witness_left",
                "split",
                "split",
                "exact hsum_witness_witness_right_left",
                "exact hprefix",
                "split",
                "rewrite ha",
                "rewrite ha",
                "exact hlast_witness_right",
                "exact hsum_witness_witness_right_right",
            ),
            "A successor count is its prefix count plus a final zero-or-one bit.",
        ),
        spec(
            "bit_count_bounded",
            BIT_COUNT_BOUNDED,
            (
                "bit_count_zero",
                "bit_count_succ_decompose",
                "add_succ_left",
                "add_assoc",
            ),
            (
                "intro b",
                "intro c",
                "induction l",
                "intro n",
                "intro hcount",
                "have hn : n = 0",
                "specialize bit_count_zero b",
                "specialize bit_count_zero c",
                "specialize bit_count_zero 0",
                "specialize bit_count_zero n",
                "apply bit_count_zero",
                "refl",
                "exact hcount",
                "exists 0",
                "rewrite hn",
                "rewrite PA3",
                "refl",
                "intro n",
                "intro hcount",
                f"have hdecomp : {successor_decomposition}",
                "specialize bit_count_succ_decompose b",
                "specialize bit_count_succ_decompose c",
                "specialize bit_count_succ_decompose l",
                "specialize bit_count_succ_decompose (S l)",
                "specialize bit_count_succ_decompose n",
                "apply bit_count_succ_decompose",
                "refl",
                "exact hcount",
                "cases hdecomp",
                "cases hdecomp_witness",
                "cases hdecomp_witness_witness",
                "cases hdecomp_witness_witness_right",
                "cases hdecomp_witness_witness_right_right",
                "have hr : exists h. h + x1 = l",
                "specialize IH x1",
                "apply IH",
                "exact hdecomp_witness_witness_right_left",
                "cases hr",
                "cases hdecomp_witness_witness_right_right_left",
                "exists S x2",
                "rewrite hdecomp_witness_witness_right_right_right",
                "rewrite hdecomp_witness_witness_right_right_left_left",
                "rewrite PA3",
                "specialize add_succ_left x2",
                "specialize add_succ_left x1",
                "rewrite add_succ_left",
                "congr",
                "exact hr_witness",
                "exists x2",
                "rewrite hdecomp_witness_witness_right_right_right",
                "rewrite hdecomp_witness_witness_right_right_left_right",
                "trans (x2 + x1) + 1",
                "symm",
                "apply add_assoc",
                "rewrite PA4",
                "rewrite PA3",
                "congr",
                "exact hr_witness",
            ),
            "A zero/one count never exceeds the length of its decoded prefix.",
        ),
    )


__all__ = ["make_finite_bitcount_theorems"]
