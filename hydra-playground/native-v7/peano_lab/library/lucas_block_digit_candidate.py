def _choose(upper: str, lower: str, value: str, *, tag: str) -> str:
    return _choose_relation_term(
        upper,
        lower,
        value,
        tag=f"lucas_block_digit_{tag}",
        variables=("p", "q", "r", "d", "e", "C", "A", "B", "n", "k"),
    )


def _lt(left: str, right: str, *, tag: str) -> str:
    return f"exists lbd_gap_{tag}. lbd_gap_{tag} + S ({left}) = ({right})"


def _mod(modulus: str, left: str, right: str, *, tag: str) -> str:
    return (
        f"exists lbd_left_{tag} lbd_right_{tag}. "
        f"({left}) + ({modulus}) * lbd_left_{tag} = "
        f"({right}) + ({modulus}) * lbd_right_{tag}"
    )


