"""Constructive affine-collision transport to divisible two-square norms.

Balanced congruence avoids subtraction: natural coordinate differences are
chosen constructively, and the two possible sign patterns are handled by
direct or opposite linear congruences.  All relations expand into the
unchanged first-order language ``{0,S,+,*,=}``; nothing is registered.
"""

from __future__ import annotations

from typing import Any, Callable


def _mod(modulus: str, left: str, right: str, *, tag: str) -> str:
    return (
        f"exists ftcn_left_{tag} ftcn_right_{tag}. "
        f"({left}) + ({modulus}) * ftcn_left_{tag} = "
        f"({right}) + ({modulus}) * ftcn_right_{tag}"
    )


def _multiple(modulus: str, value: str, *, tag: str) -> str:
    return f"exists ftcn_factor_{tag}. ({value}) = ({modulus}) * ftcn_factor_{tag}"


def _difference(left: str, right: str, value: str) -> str:
    return f"(({left}) = ({right}) + ({value}) \\/ ({right}) = ({left}) + ({value}))"


def _le(left: str, right: str, *, tag: str) -> str:
    return f"exists ftcn_bound_{tag}. ftcn_bound_{tag} + ({left}) = ({right})"


def _lt(left: str, right: str, *, tag: str) -> str:
    return f"exists ftcn_strict_{tag}. ftcn_strict_{tag} + S ({left}) = ({right})"


