"""Constructive bounded Euler-criterion packaging.

For an odd prime represented by ``p = S n`` and ``n = h+h``, the two
already isolated Euler endpoints give the residues ``1`` and ``n = p-1``.
This module proves those residues distinct, derives nondivisibility from the
canonical assumptions ``a != 0`` and ``a < p``, and packages both directions
of the residue and nonresidue classifications.

All displayed surfaces expand to unchanged first-order Peano arithmetic.
The candidates are dependency-curried, constructive, unregistered, and
unadmitted.
"""

from __future__ import annotations

from typing import Any, Callable

from .euler_scaled_inverse_candidate import prime
from .fermat_residue_map_candidate import not_divides
from .finite_fold_surface import power_relation
from .quadratic_residue_surface import quadratic_residue
from .wilson_pair_order_candidate import _lt_term
from .wilson_pair_product_candidate import _mod_eq_term


def make_euler_criterion_bounded_candidate_theorems(
    spec: Callable[..., Any],
) -> tuple[Any, ...]:
    """Build bounded-unit, residue-separation, and complete Euler contracts."""

    variables = ("p", "a", "n", "h", "A")
    prime_p = prime("p", tag="ecb_prime")
    a_lt_p = _lt_term(
        "a", "p", tag="ecb_a_lt_p", avoid=variables
    )
    not_divisor = not_divides("p", "a", tag="ecb_not_divisor")
    qres = quadratic_residue("p", "a", tag="ecb_qres")
    power = power_relation("a", "h", "A", tag="ecb_power")
    mod_one = _mod_eq_term(
        "p", "A", "1", tag="ecb_mod_one", avoid=variables
    )
    mod_predecessor = _mod_eq_term(
        "p", "A", "n", tag="ecb_mod_predecessor", avoid=variables
    )
    one_mod_predecessor = _mod_eq_term(
        "p", "1", "n", tag="ecb_one_mod_predecessor", avoid=variables
    )
    residue_iff = f"((({qres}) -> ({mod_one})) /\\ (({mod_one}) -> ({qres})))"
    nonresidue_iff = (
        f"((~({qres}) -> ({mod_predecessor})) /\\ "
        f"(({mod_predecessor}) -> ~({qres})))"
    )
    dichotomy = (
        f"((({qres}) /\\ ({mod_one})) \/ "
        f"((~({qres})) /\\ ({mod_predecessor})))"
    )

    return (
        spec(
            "bounded_nonzero_not_divides",
            f"forall p a. ~(a = 0) -> ({a_lt_p}) -> ({not_divisor})",
            ("divisor_le_nonzero", "lt_not_le"),
            (
                "intro p",
                "intro a",
                "intro ha0",
                "intro hap",
                "intro hdiv",
                "have hpa : exists t. t + p = a",
                "specialize divisor_le_nonzero p",
                "specialize divisor_le_nonzero a",
                "apply divisor_le_nonzero",
                "exact ha0",
                "exact hdiv",
                "specialize lt_not_le a",
                "specialize lt_not_le p",
                "apply lt_not_le",
                "exact hap",
                "exact hpa",
            ),
            "A nonzero value strictly below a modulus is not divisible by it.",
        ),
        spec(
            "double_predecessor_ne_one",
            "forall n h. n = h + h -> ~(n = 1)",
            ("even_odd_exclusive_pointwise", "mul_comm", "zero_add"),
            (
                "intro n",
                "intro h",
                "intro heven",
                "intro hone",
                "have heven_two : n = 2 * h",
                "trans h + h",
                "exact heven",
                "trans h * 2",
                "simp [zero_add]",
                "specialize mul_comm h",
                "specialize mul_comm 2",
                "apply mul_comm",
                "have hone_odd : n = 2 * 0 + 1",
                "rewrite hone",
                "norm_num",
                "specialize even_odd_exclusive_pointwise n",
                "specialize even_odd_exclusive_pointwise h",
                "specialize even_odd_exclusive_pointwise 0",
                "apply even_odd_exclusive_pointwise",
                "exact heven_two",
                "exact hone_odd",
            ),
            "A doubled predecessor cannot equal one.",
        ),
        spec(
            "odd_prime_one_not_mod_predecessor",
            "forall p n h. p = S n -> "
            f"({prime_p}) -> n = h + h -> ~({one_mod_predecessor})",
            (
                "double_predecessor_ne_one",
                "prime_is_succ_succ",
                "mod_eq_bounded_unique",
                "zero_add",
            ),
            (
                "intro p",
                "intro n",
                "intro h",
                "intro hpn",
                "intro hp",
                "intro heven",
                "intro hone_mod",
                "have hp_shape : exists k. p = S (S k)",
                "specialize prime_is_succ_succ p",
                "apply prime_is_succ_succ",
                "exact hp",
                "cases hp_shape",
                "have h1p : exists gap. gap + S 1 = p",
                "exists x",
                "rewrite hp_shape_witness",
                "simp",
                "have hnp : exists gap. gap + S n = p",
                "exists 0",
                "trans S n",
                "apply zero_add",
                "symm",
                "exact hpn",
                "have h1n : 1 = n",
                "specialize mod_eq_bounded_unique p",
                "specialize mod_eq_bounded_unique 1",
                "specialize mod_eq_bounded_unique n",
                "apply mod_eq_bounded_unique",
                "exact h1p",
                "exact hnp",
                "exact hone_mod",
                "specialize double_predecessor_ne_one n",
                "specialize double_predecessor_ne_one h",
                "apply double_predecessor_ne_one",
                "exact heven",
                "symm",
                "exact h1n",
            ),
            "For an odd-prime predecessor, the canonical residues one and p-1 are distinct.",
        ),
        spec(
            "bounded_euler_criterion_dichotomy",
            "forall p a n h A. p = S n -> "
            f"({prime_p}) -> ~(a = 0) -> ({a_lt_p}) -> n = h + h -> "
            f"({power}) -> ({dichotomy})",
            (
                "prime_nonzero",
                "bounded_nonzero_not_divides",
                "quadratic_residue_decidable_nonzero",
                "quadratic_residue_half_power_mod_one",
                "quadratic_nonresidue_half_power_mod_predecessor",
                "add_succ_left",
                "mul_comm",
                "zero_add",
            ),
            (
                "intro p",
                "intro a",
                "intro n",
                "intro h",
                "intro A",
                "intro hpn",
                "intro hp",
                "intro ha0",
                "intro hap",
                "intro heven",
                "intro hpower",
                "have hp0 : ~(p = 0)",
                "intro hpzero",
                "specialize prime_nonzero p",
                "apply prime_nonzero",
                "exact hp",
                "exact hpzero",
                f"have hnotdiv : {not_divisor}",
                "intro hdiv",
                "specialize bounded_nonzero_not_divides p",
                "specialize bounded_nonzero_not_divides a",
                "apply bounded_nonzero_not_divides",
                "exact ha0",
                "exact hap",
                "exact hdiv",
                "have hdouble : h + h = 2 * h",
                "trans h * 2",
                "simp [zero_add]",
                "specialize mul_comm h",
                "specialize mul_comm 2",
                "apply mul_comm",
                "have hodd : p = 2 * h + 1",
                "trans S n",
                "exact hpn",
                "rewrite heven",
                "rewrite hdouble",
                "simp [add_succ_left]",
                f"have hdec : ({qres}) \/ ~({qres})",
                "specialize quadratic_residue_decidable_nonzero p",
                "specialize quadratic_residue_decidable_nonzero a",
                "apply quadratic_residue_decidable_nonzero",
                "exact hp0",
                "cases hdec",
                "left",
                "split",
                "exact hdec_left",
                "specialize quadratic_residue_half_power_mod_one p",
                "specialize quadratic_residue_half_power_mod_one h",
                "specialize quadratic_residue_half_power_mod_one a",
                "specialize quadratic_residue_half_power_mod_one A",
                "apply quadratic_residue_half_power_mod_one",
                "exact hodd",
                "exact hp",
                "exact hnotdiv",
                "exact hdec_left",
                "exact hpower",
                "right",
                "split",
                "exact hdec_right",
                "specialize quadratic_nonresidue_half_power_mod_predecessor p",
                "specialize quadratic_nonresidue_half_power_mod_predecessor a",
                "specialize quadratic_nonresidue_half_power_mod_predecessor n",
                "specialize quadratic_nonresidue_half_power_mod_predecessor h",
                "specialize quadratic_nonresidue_half_power_mod_predecessor A",
                "apply quadratic_nonresidue_half_power_mod_predecessor",
                "exact hpn",
                "exact hp",
                "exact ha0",
                "exact hap",
                "exact hdec_right",
                "exact heven",
                "exact hpower",
            ),
            "Every bounded nonzero input lands constructively in exactly the appropriate Euler endpoint.",
        ),
        spec(
            "bounded_euler_criterion_residue_iff",
            "forall p a n h A. p = S n -> "
            f"({prime_p}) -> ~(a = 0) -> ({a_lt_p}) -> n = h + h -> "
            f"({power}) -> ({residue_iff})",
            (
                "bounded_euler_criterion_dichotomy",
                "odd_prime_one_not_mod_predecessor",
                "mod_eq_symm",
                "mod_eq_trans",
            ),
            (
                "intro p",
                "intro a",
                "intro n",
                "intro h",
                "intro A",
                "intro hpn",
                "intro hp",
                "intro ha0",
                "intro hap",
                "intro heven",
                "intro hpower",
                f"have hdichotomy : {dichotomy}",
                "specialize bounded_euler_criterion_dichotomy p",
                "specialize bounded_euler_criterion_dichotomy a",
                "specialize bounded_euler_criterion_dichotomy n",
                "specialize bounded_euler_criterion_dichotomy h",
                "specialize bounded_euler_criterion_dichotomy A",
                "apply bounded_euler_criterion_dichotomy",
                "exact hpn",
                "exact hp",
                "exact ha0",
                "exact hap",
                "exact heven",
                "exact hpower",
                f"have hdistinct : ~({one_mod_predecessor})",
                "intro hcollision",
                "specialize odd_prime_one_not_mod_predecessor p",
                "specialize odd_prime_one_not_mod_predecessor n",
                "specialize odd_prime_one_not_mod_predecessor h",
                "apply odd_prime_one_not_mod_predecessor",
                "exact hpn",
                "exact hp",
                "exact heven",
                "exact hcollision",
                "split",
                "intro hqres",
                "cases hdichotomy",
                "cases hdichotomy_left",
                "exact hdichotomy_left_right",
                "cases hdichotomy_right",
                "exfalso",
                "apply hdichotomy_right_left",
                "exact hqres",
                "intro hone",
                "cases hdichotomy",
                "cases hdichotomy_left",
                "exact hdichotomy_left_left",
                "cases hdichotomy_right",
                "exfalso",
                "apply hdistinct",
                f"have hone_back : {_mod_eq_term('p', '1', 'A', tag='ecb_one_back', avoid=variables)}",
                "specialize mod_eq_symm p",
                "specialize mod_eq_symm A",
                "specialize mod_eq_symm 1",
                "apply mod_eq_symm",
                "exact hone",
                "specialize mod_eq_trans p",
                "specialize mod_eq_trans 1",
                "specialize mod_eq_trans A",
                "specialize mod_eq_trans n",
                "apply mod_eq_trans",
                "exact hone_back",
                "exact hdichotomy_right_right",
            ),
            "For bounded nonzero inputs, quadratic residuosity is equivalent to the half-power residue one.",
        ),
        spec(
            "bounded_euler_criterion_nonresidue_iff",
            "forall p a n h A. p = S n -> "
            f"({prime_p}) -> ~(a = 0) -> ({a_lt_p}) -> n = h + h -> "
            f"({power}) -> ({nonresidue_iff})",
            (
                "bounded_euler_criterion_dichotomy",
                "bounded_euler_criterion_residue_iff",
                "odd_prime_one_not_mod_predecessor",
                "mod_eq_symm",
                "mod_eq_trans",
            ),
            (
                "intro p",
                "intro a",
                "intro n",
                "intro h",
                "intro A",
                "intro hpn",
                "intro hp",
                "intro ha0",
                "intro hap",
                "intro heven",
                "intro hpower",
                f"have hdichotomy : {dichotomy}",
                "specialize bounded_euler_criterion_dichotomy p",
                "specialize bounded_euler_criterion_dichotomy a",
                "specialize bounded_euler_criterion_dichotomy n",
                "specialize bounded_euler_criterion_dichotomy h",
                "specialize bounded_euler_criterion_dichotomy A",
                "apply bounded_euler_criterion_dichotomy",
                "exact hpn",
                "exact hp",
                "exact ha0",
                "exact hap",
                "exact heven",
                "exact hpower",
                f"have hresidue_iff : {residue_iff}",
                "specialize bounded_euler_criterion_residue_iff p",
                "specialize bounded_euler_criterion_residue_iff a",
                "specialize bounded_euler_criterion_residue_iff n",
                "specialize bounded_euler_criterion_residue_iff h",
                "specialize bounded_euler_criterion_residue_iff A",
                "apply bounded_euler_criterion_residue_iff",
                "exact hpn",
                "exact hp",
                "exact ha0",
                "exact hap",
                "exact heven",
                "exact hpower",
                f"have hdistinct : ~({one_mod_predecessor})",
                "intro hcollision",
                "specialize odd_prime_one_not_mod_predecessor p",
                "specialize odd_prime_one_not_mod_predecessor n",
                "specialize odd_prime_one_not_mod_predecessor h",
                "apply odd_prime_one_not_mod_predecessor",
                "exact hpn",
                "exact hp",
                "exact heven",
                "exact hcollision",
                "split",
                "intro hnonresidue",
                "cases hdichotomy",
                "cases hdichotomy_left",
                "exfalso",
                "apply hnonresidue",
                "exact hdichotomy_left_left",
                "cases hdichotomy_right",
                "exact hdichotomy_right_right",
                "intro hminus",
                "intro hqres",
                "cases hresidue_iff",
                f"have hone : {mod_one}",
                "apply hresidue_iff_left",
                "exact hqres",
                "apply hdistinct",
                f"have hone_back : {_mod_eq_term('p', '1', 'A', tag='ecb_nonresidue_one_back', avoid=variables)}",
                "specialize mod_eq_symm p",
                "specialize mod_eq_symm A",
                "specialize mod_eq_symm 1",
                "apply mod_eq_symm",
                "exact hone",
                "specialize mod_eq_trans p",
                "specialize mod_eq_trans 1",
                "specialize mod_eq_trans A",
                "specialize mod_eq_trans n",
                "apply mod_eq_trans",
                "exact hone_back",
                "exact hminus",
            ),
            "For bounded nonzero inputs, nonresiduosity is equivalent to the half-power residue p-1.",
        ),
        spec(
            "bounded_euler_criterion_complete",
            "forall p a n h A. p = S n -> "
            f"({prime_p}) -> ~(a = 0) -> ({a_lt_p}) -> n = h + h -> "
            f"({power}) -> (({residue_iff}) /\\ ({nonresidue_iff}))",
            (
                "bounded_euler_criterion_residue_iff",
                "bounded_euler_criterion_nonresidue_iff",
            ),
            (
                "intro p",
                "intro a",
                "intro n",
                "intro h",
                "intro A",
                "intro hpn",
                "intro hp",
                "intro ha0",
                "intro hap",
                "intro heven",
                "intro hpower",
                "split",
                "specialize bounded_euler_criterion_residue_iff p",
                "specialize bounded_euler_criterion_residue_iff a",
                "specialize bounded_euler_criterion_residue_iff n",
                "specialize bounded_euler_criterion_residue_iff h",
                "specialize bounded_euler_criterion_residue_iff A",
                "apply bounded_euler_criterion_residue_iff",
                "exact hpn",
                "exact hp",
                "exact ha0",
                "exact hap",
                "exact heven",
                "exact hpower",
                "specialize bounded_euler_criterion_nonresidue_iff p",
                "specialize bounded_euler_criterion_nonresidue_iff a",
                "specialize bounded_euler_criterion_nonresidue_iff n",
                "specialize bounded_euler_criterion_nonresidue_iff h",
                "specialize bounded_euler_criterion_nonresidue_iff A",
                "apply bounded_euler_criterion_nonresidue_iff",
                "exact hpn",
                "exact hp",
                "exact ha0",
                "exact hap",
                "exact heven",
                "exact hpower",
            ),
            "Complete bounded Euler criterion, including both residue and nonresidue equivalences.",
        ),
    )


__all__ = ["make_euler_criterion_bounded_candidate_theorems"]
