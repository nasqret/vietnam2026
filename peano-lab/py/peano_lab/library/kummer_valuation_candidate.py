                "have htotal : exists z. "
                + factorial_valuation("p", "n", "z", tag="kmvclvb_total_factorial"),
                "specialize factorial_valuation_exists p",
                "specialize factorial_valuation_exists n",
                "exact factorial_valuation_exists",
                "cases htotal",
                "have hleft : exists z. "
                + factorial_valuation("p", "k", "z", tag="kmvclvb_left_factorial"),
