def _grid_point(index: str, *, tag: str) -> str:
    entry = beta_at("b", "c", index, "t", tag=f"ftpr_point_{tag}")
    return (
        "exists i j q t. "
        f"(({index}) = (S s) * i + j /\\ "
        f"(({_lt('j', 'S s', tag=f'point_{tag}_column')}) /\\ "
        f"((r * i + j = (p) * q + t) /\\ "
        f"(({_lt('t', 'p', tag=f'point_{tag}_residue')}) /\\ ({entry})))))"
    )


