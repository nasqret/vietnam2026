"""Native parity and small-modulus foundations for quadratic reciprocity.

The object language has no predicate-definition mechanism, so ``Even`` and
``Odd`` are deliberately expanded in every public statement as witnesses of
the forms ``n = 2 * k`` and ``n = 2 * k + 1``.  This module is untrusted
library data: :mod:`peano_lab.library.theorems` replays every script and asks
the independent PA kernel to check the resulting closed certificate.

Keeping this tranche in a separate source file makes the quadratic-
reciprocity campaign reviewable without changing the kernel or parser.
"""

from __future__ import annotations

from typing import Any, Callable


def make_parity_theorems(spec: Callable[..., Any]) -> tuple[Any, ...]:
    """Build the ordered QR-0 parity ladder with the host ``TheoremSpec``."""

    return (
        spec(
            "parity_cases",
            "forall n. exists k. n = 2 * k \\/ n = 2 * k + 1",
            (),
            (
                "induction n",
                "exists 0",
                "left",
                "norm_num",
                "cases IH",
                "cases IH_witness",
                "exists x",
                "right",
                "rewrite IH_witness_left",
                "simp",
                "exists x + 1",
                "left",
                "rewrite IH_witness_right",
                "simp",
            ),
            "Every natural has a constructive even-or-odd witness.",
        ),
        spec(
            "even_odd_exclusive_pointwise",
            "forall n a b. n = 2 * a -> n = 2 * b + 1 -> false",
            ("division_remainder_unique",),
            (
                "intro n",
                "intro a",
                "intro b",
                "intro he",
                "intro ho",
                "have hu : a = b /\\ 0 = 1",
                "specialize division_remainder_unique 2",
                "specialize division_remainder_unique n",
                "specialize division_remainder_unique a",
                "specialize division_remainder_unique 0",
                "specialize division_remainder_unique b",
                "specialize division_remainder_unique 1",
                "apply division_remainder_unique",
                "rewrite he",
                "simp",
                "exists 1",
                "norm_num",
                "exact ho",
                "exists 0",
                "norm_num",
                "cases hu",
                "apply PA1",
                "symm",
                "exact hu_right",
            ),
            "An even and an odd decomposition of the same natural are incompatible.",
        ),
        spec(
            "even_not_odd",
            "forall n. (exists a. n = 2 * a) -> ~(exists b. n = 2 * b + 1)",
            ("even_odd_exclusive_pointwise",),
            (
                "intro n",
                "intro he",
                "intro ho",
                "cases he",
                "cases ho",
                "specialize even_odd_exclusive_pointwise n",
                "specialize even_odd_exclusive_pointwise x",
                "specialize even_odd_exclusive_pointwise x1",
                "apply even_odd_exclusive_pointwise",
                "exact he_witness",
                "exact ho_witness",
            ),
            "No even natural is odd.",
        ),
        spec(
            "odd_not_even",
            "forall n. (exists b. n = 2 * b + 1) -> ~(exists a. n = 2 * a)",
            ("even_odd_exclusive_pointwise",),
            (
                "intro n",
                "intro ho",
                "intro he",
                "cases ho",
                "cases he",
                "specialize even_odd_exclusive_pointwise n",
                "specialize even_odd_exclusive_pointwise x1",
                "specialize even_odd_exclusive_pointwise x",
                "apply even_odd_exclusive_pointwise",
                "exact he_witness",
                "exact ho_witness",
            ),
            "No odd natural is even.",
        ),
        spec(
            "successor_odd_of_even",
            "forall n. (exists a. n = 2 * a) -> exists b. S n = 2 * b + 1",
            (),
            (
                "intro n",
                "intro he",
                "cases he",
                "exists x",
                "rewrite he_witness",
                "simp",
            ),
            "The successor of an even natural is odd.",
        ),
        spec(
            "successor_even_of_odd",
            "forall n. (exists a. n = 2 * a + 1) -> exists b. S n = 2 * b",
            (),
            (
                "intro n",
                "intro ho",
                "cases ho",
                "exists x + 1",
                "rewrite ho_witness",
                "simp",
            ),
            "The successor of an odd natural is even.",
        ),
        spec(
            "even_add_even",
            "forall m n. (exists a. m = 2 * a) -> (exists b. n = 2 * b) -> "
            "exists c. m + n = 2 * c",
            ("mul_add",),
            (
                "intro m",
                "intro n",
                "intro hm",
                "intro hn",
                "cases hm",
                "cases hn",
                "exists x + x1",
                "rewrite hm_witness",
                "rewrite hn_witness",
                "simp [mul_add]",
            ),
            "The sum of two even naturals is even.",
        ),
        spec(
            "even_add_odd",
            "forall m n. (exists a. m = 2 * a) -> (exists b. n = 2 * b + 1) -> "
            "exists c. m + n = 2 * c + 1",
            ("mul_add", "add_assoc"),
            (
                "intro m",
                "intro n",
                "intro hm",
                "intro hn",
                "cases hm",
                "cases hn",
                "exists x + x1",
                "rewrite hm_witness",
                "rewrite hn_witness",
                "simp [mul_add, add_assoc]",
            ),
            "An even natural plus an odd natural is odd.",
        ),
        spec(
            "odd_add_even",
            "forall m n. (exists a. m = 2 * a + 1) -> (exists b. n = 2 * b) -> "
            "exists c. m + n = 2 * c + 1",
            ("mul_add", "add_succ_left"),
            (
                "intro m",
                "intro n",
                "intro hm",
                "intro hn",
                "cases hm",
                "cases hn",
                "exists x + x1",
                "rewrite hm_witness",
                "rewrite hn_witness",
                "simp [mul_add, add_succ_left]",
            ),
            "An odd natural plus an even natural is odd.",
        ),
        spec(
            "odd_add_odd",
            "forall m n. (exists a. m = 2 * a + 1) -> "
            "(exists b. n = 2 * b + 1) -> exists c. m + n = 2 * c",
            ("mul_add", "add_succ_left", "add_assoc", "add_comm"),
            (
                "intro m",
                "intro n",
                "intro hm",
                "intro hn",
                "cases hm",
                "cases hn",
                "exists x + x1 + 1",
                "rewrite hm_witness",
                "rewrite hn_witness",
                "simp [mul_add, add_assoc, add_comm]",
            ),
            "The sum of two odd naturals is even.",
        ),
        spec(
            "even_mul_left",
            "forall m n. (exists a. m = 2 * a) -> exists c. m * n = 2 * c",
            ("mul_assoc",),
            (
                "intro m",
                "intro n",
                "intro hm",
                "cases hm",
                "exists x * n",
                "rewrite hm_witness",
                "apply mul_assoc",
            ),
            "A product with an even left factor is even.",
        ),
        spec(
            "mul_double_right",
            "forall m b. m * (2 * b) = 2 * (m * b)",
            ("mul_assoc", "mul_comm"),
            (
                "intro m",
                "intro b",
                "trans (2 * b) * m",
                "apply mul_comm",
                "trans 2 * (b * m)",
                "apply mul_assoc",
                "congr",
                "refl",
                "apply mul_comm",
            ),
            "Doubling commutes through multiplication on the right.",
        ),
        spec(
            "even_mul_right",
            "forall m n. (exists b. n = 2 * b) -> exists c. m * n = 2 * c",
            ("mul_double_right",),
            (
                "intro m",
                "intro n",
                "intro hn",
                "cases hn",
                "exists m * x",
                "rewrite hn_witness",
                "apply mul_double_right",
            ),
            "A product with an even right factor is even.",
        ),
        spec(
            "odd_mul_odd",
            "forall m n. (exists a. m = 2 * a + 1) -> "
            "(exists b. n = 2 * b + 1) -> exists c. m * n = 2 * c + 1",
            (
                "mul_add",
                "add_mul",
                "add_assoc",
                "add_succ_left",
                "mul_double_right",
            ),
            (
                "intro m",
                "intro n",
                "intro hm",
                "intro hn",
                "cases hm",
                "cases hn",
                "exists (2 * x + 1) * x1 + x",
                "rewrite hm_witness",
                "rewrite hn_witness",
                "simp [mul_add, add_mul, add_assoc, add_succ_left]",
                "congr",
                "congr",
                "apply mul_double_right",
                "refl",
            ),
            "The product of two odd naturals is odd.",
        ),
        spec(
            "odd_half_unique",
            "forall n a b. n = 2 * a + 1 -> n = 2 * b + 1 -> a = b",
            ("add_right_cancel", "mul_left_cancel_nonzero"),
            (
                "intro n",
                "intro a",
                "intro b",
                "intro ha",
                "intro hb",
                "have hs : 2 * a + 1 = 2 * b + 1",
                "trans n",
                "symm",
                "exact ha",
                "exact hb",
                "have hm : 2 * a = 2 * b",
                "specialize add_right_cancel (2 * a)",
                "specialize add_right_cancel (2 * b)",
                "specialize add_right_cancel 1",
                "apply add_right_cancel",
                "exact hs",
                "specialize mul_left_cancel_nonzero 2",
                "specialize mul_left_cancel_nonzero a",
                "specialize mul_left_cancel_nonzero b",
                "apply mul_left_cancel_nonzero",
                "intro htwo",
                "apply PA1",
                "exact htwo",
                "exact hm",
            ),
            "The half witness in an odd decomposition is unique.",
        ),
        spec(
            "odd_half_exists_unique",
            "forall n. (exists a. n = 2 * a + 1) -> exists h. "
            "n = 2 * h + 1 /\\ forall k. n = 2 * k + 1 -> h = k",
            ("odd_half_unique",),
            (
                "intro n",
                "intro ho",
                "cases ho",
                "exists x",
                "split",
                "exact ho_witness",
                "intro k",
                "intro hk",
                "specialize odd_half_unique n",
                "specialize odd_half_unique x",
                "specialize odd_half_unique k",
                "apply odd_half_unique",
                "exact ho_witness",
                "exact hk",
            ),
            "Every odd natural has a unique half witness.",
        ),
        spec(
            "four_mul_eq_double_double",
            "forall a. 4 * a = 2 * (2 * a)",
            ("mul_assoc",),
            (
                "intro a",
                "trans (2 * 2) * a",
                "congr",
                "norm_num",
                "refl",
                "apply mul_assoc",
            ),
            "Multiplication by four is iterated doubling.",
        ),
        spec(
            "odd_mod4_cases",
            "forall n. (exists h. n = 2 * h + 1) -> "
            "(exists a. n = 4 * a + 1) \\/ exists b. n = 4 * b + 3",
            ("parity_cases", "mul_add", "four_mul_eq_double_double"),
            (
                "intro n",
                "intro ho",
                "cases ho",
                "specialize parity_cases x",
                "cases parity_cases",
                "cases parity_cases_witness",
                "left",
                "exists x1",
                "rewrite ho_witness",
                "rewrite parity_cases_witness_left",
                "simp [mul_add]",
                "congr",
                "symm",
                "apply four_mul_eq_double_double",
                "right",
                "exists x1",
                "rewrite ho_witness",
                "rewrite parity_cases_witness_right",
                "simp [mul_add]",
                "congr",
                "congr",
                "congr",
                "symm",
                "apply four_mul_eq_double_double",
            ),
            "Every odd natural is congruent to one or three modulo four.",
        ),
        spec(
            "mod4_one_three_exclusive_pointwise",
            "forall n a b. n = 4 * a + 1 -> n = 4 * b + 3 -> false",
            ("division_remainder_unique",),
            (
                "intro n",
                "intro a",
                "intro b",
                "intro h1",
                "intro h3",
                "have hu : a = b /\\ 1 = 3",
                "specialize division_remainder_unique 4",
                "specialize division_remainder_unique n",
                "specialize division_remainder_unique a",
                "specialize division_remainder_unique 1",
                "specialize division_remainder_unique b",
                "specialize division_remainder_unique 3",
                "apply division_remainder_unique",
                "exact h1",
                "exists 2",
                "norm_num",
                "exact h3",
                "exists 0",
                "norm_num",
                "cases hu",
                "have hz : 0 = 2",
                "apply PA2",
                "exact hu_right",
                "apply PA1",
                "symm",
                "exact hz",
            ),
            "Residues one and three modulo four cannot describe the same natural.",
        ),
        spec(
            "mod4_one_is_odd",
            "forall n. (exists a. n = 4 * a + 1) -> exists h. n = 2 * h + 1",
            ("four_mul_eq_double_double",),
            (
                "intro n",
                "intro h",
                "cases h",
                "exists 2 * x",
                "rewrite h_witness",
                "congr",
                "apply four_mul_eq_double_double",
                "refl",
            ),
            "A natural congruent to one modulo four is odd.",
        ),
        spec(
            "mod4_three_is_odd",
            "forall n. (exists a. n = 4 * a + 3) -> exists h. n = 2 * h + 1",
            ("mul_add", "four_mul_eq_double_double"),
            (
                "intro n",
                "intro h",
                "cases h",
                "exists 2 * x + 1",
                "rewrite h_witness",
                "simp [mul_add]",
                "congr",
                "congr",
                "congr",
                "apply four_mul_eq_double_double",
            ),
            "A natural congruent to three modulo four is odd.",
        ),
        spec(
            "prime_ne_two_is_odd",
            "forall p. (~(p = 1) /\\ forall a b. p = a * b -> "
            "a = 1 \\/ b = 1) -> ~(p = 2) -> exists h. p = 2 * h + 1",
            ("parity_cases",),
            (
                "intro p",
                "intro hp",
                "intro hne",
                "cases hp",
                "specialize parity_cases p",
                "cases parity_cases",
                "cases parity_cases_witness",
                "have hfac : 2 = 1 \\/ x = 1",
                "specialize hp_right 2",
                "specialize hp_right x",
                "apply hp_right",
                "exact parity_cases_witness_left",
                "cases hfac",
                "exfalso",
                "apply PA1",
                "apply PA2",
                "exact hfac_left",
                "exfalso",
                "apply hne",
                "trans 2 * x",
                "exact parity_cases_witness_left",
                "rewrite hfac_right",
                "simp",
                "exists x",
                "exact parity_cases_witness_right",
            ),
            "Every prime other than two is odd.",
        ),
    )


__all__ = ["make_parity_theorems"]
