def _two_square(value: str, *, tag: str) -> str:
    """Expand witnessed two-square representation in the native HA language."""

    first = f"ftsc_first_{tag}"
    second = f"ftsc_second_{tag}"
    return f"exists {first} {second}. ({value}) = {first} * {first} + {second} * {second}"


def _four_three(value: str, *, tag: str) -> str:
    return f"exists ftsc_four_three_{tag}. ({value}) = 4 * ftsc_four_three_{tag} + 3"


def _four_one(value: str, *, tag: str) -> str:
    return f"exists ftsc_four_one_{tag}. ({value}) = 4 * ftsc_four_one_{tag} + 1"


def _odd(value: str, *, tag: str) -> str:
    return f"exists ftsc_odd_{tag}. ({value}) = 2 * ftsc_odd_{tag} + 1"


def _gap_branch(variable: str) -> tuple[str, ...]:
    """Move the magnitude square past three additive terms constructively."""

    return (
        f"trans {variable} * {variable} + "
        f"(m * m + (m * {variable} + (m * {variable} + {variable} * {variable})))",
        "apply two_square_add_swap_nested",
        f"trans {variable} * {variable} + "
        f"(m * {variable} + (m * m + (m * {variable} + {variable} * {variable})))",
        "congr",
        "refl",
        "apply two_square_add_swap_nested",
        "congr",
        "refl",
        "congr",
        "refl",
        "apply two_square_add_swap_nested",
    )


