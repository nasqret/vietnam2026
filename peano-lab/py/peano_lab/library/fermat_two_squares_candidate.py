"""Constructive first-order foundations for Fermat's two-square theorem.

The first supplementary law supplies an actual natural root of ``-1`` modulo
every prime congruent to one modulo four.  This tranche turns that root into
an explicit divisible norm, develops the elementary modulo-four obstruction,
and proves the final bounded-multiple step needed by a future pigeonhole or
Euclidean-descent construction.

Every contract expands into the unchanged first-order language
``{0,S,+,*,=}``.  These isolated, dependency-curried candidates are neither
registered public theorems nor a proof of the full two-square theorem.
"""

from __future__ import annotations

