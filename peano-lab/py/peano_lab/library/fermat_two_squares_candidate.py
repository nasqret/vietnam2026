def _four_residue(value: str, remainder: int, *, tag: str) -> str:
    return (
        f"exists fts_four_{tag}. "
        f"{value} = 4 * fts_four_{tag} + {remainder}"
    )


def _strict_below(left: str, right: str, *, tag: str) -> str:
    return f"exists fts_gap_{tag}. fts_gap_{tag} + S ({left}) = {right}"


def _divides(divisor: str, value: str, *, tag: str) -> str:
    return f"exists fts_factor_{tag}. {value} = {divisor} * fts_factor_{tag}"


