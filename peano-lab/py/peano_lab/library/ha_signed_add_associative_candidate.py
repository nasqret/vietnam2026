"""Strict-HA associativity candidates for canonical signed addition.

The tranche isolates the only nontrivial natural-arithmetic calculation in
two reusable lemmas, then transports three exact RFC D05 graphs through that
calculation.  All proofs are constructive, dependency-curried, unregistered,
and unadmitted.
"""

from __future__ import annotations

from typing import Any, Callable

from peano_lab.library.ha_signed_add_candidate import signed_add


def make_ha_signed_add_associative_candidate_theorems(
    spec: Callable[..., Any],
) -> tuple[Any, ...]:
    """Build the cross-sum chain, equation associator, and graph law."""

    add_ab = signed_add("a", "b", "ab", tag="assoc_ab")
    add_abc = signed_add("ab", "c", "abc", tag="assoc_abc")
    add_bc = signed_add("b", "c", "bc", tag="assoc_bc")
    add_target = signed_add("a", "bc", "abc", tag="assoc_target")

    return (
        spec(
            "add_cross_sum_chain",
            "forall a b x y c d. a + x = b + y -> "
            "y + c = x + d -> a + c = b + d",
            ("add_assoc", "add_comm", "add_left_cancel"),
            (
                "intro a",
                "intro b",
                "intro x",
                "intro y",
                "intro c",
                "intro d",
                "intro hfirst",
                "intro hsecond",
                "specialize add_left_cancel x",
                "specialize add_left_cancel (a + c)",
                "specialize add_left_cancel (b + d)",
                "apply add_left_cancel",
                "trans (x + a) + c",
                "symm",
                "apply add_assoc",
                "trans (a + x) + c",
                "congr",
                "apply add_comm",
                "refl",
                "trans (b + y) + c",
                "congr",
                "exact hfirst",
                "refl",
                "trans b + (y + c)",
                "apply add_assoc",
                "trans b + (x + d)",
                "congr",
                "refl",
                "exact hsecond",
                "trans (b + x) + d",
                "symm",
                "apply add_assoc",
                "trans (x + b) + d",
                "congr",
                "apply add_comm",
                "refl",
                "apply add_assoc",
            ),
            "Two subtraction-free cross-sum equations compose after "
            "cancelling their shared middle contribution.",
        ),
        spec(
            "signed_add_equations_associate",
            "forall ap an bp bn cp cn abp abn bcp bcn outp outn. "
            "((ap + bp) + abn = (an + bn) + abp) -> "
            "((abp + cp) + outn = (abn + cn) + outp) -> "
            "((bp + cp) + bcn = (bn + cn) + bcp) -> "
            "(ap + bcp) + outn = (an + bcn) + outp",
            (
                "add_cross_sum_chain",
                "add_assoc",
                "add_comm",
                "add_permute_outer",
            ),
            (
                "intro ap",
                "intro an",
                "intro bp",
                "intro bn",
                "intro cp",
                "intro cn",
                "intro abp",
                "intro abn",
                "intro bcp",
                "intro bcn",
                "intro outp",
                "intro outn",
                "intro hfirst",
                "intro hsecond",
                "intro hthird",
                "have hsecond_flat : "
                "abp + (cp + outn) = abn + (cn + outp)",
                "trans (abp + cp) + outn",
                "symm",
                "apply add_assoc",
                "trans (abn + cn) + outp",
                "exact hsecond",
                "apply add_assoc",
                "have htriple_flat : "
                "(ap + bp) + (cp + outn) = "
                "(an + bn) + (cn + outp)",
                "specialize add_cross_sum_chain (ap + bp)",
                "specialize add_cross_sum_chain (an + bn)",
                "specialize add_cross_sum_chain abn",
                "specialize add_cross_sum_chain abp",
                "specialize add_cross_sum_chain (cp + outn)",
                "specialize add_cross_sum_chain (cn + outp)",
                "apply add_cross_sum_chain",
                "exact hfirst",
                "exact hsecond_flat",
                "have htriple : "
                "ap + ((bp + cp) + outn) = "
                "an + ((bn + cn) + outp)",
                "trans ap + (bp + (cp + outn))",
                "congr",
                "refl",
                "apply add_assoc",
                "trans (ap + bp) + (cp + outn)",
                "symm",
                "apply add_assoc",
                "trans (an + bn) + (cn + outp)",
                "exact htriple_flat",
                "trans an + (bn + (cn + outp))",
                "apply add_assoc",
                "congr",
                "refl",
                "symm",
                "apply add_assoc",
                "have hshuffle : forall a b c d. "
                "(a + b) + (c + d) = (a + c) + (b + d)",
                "intro a",
                "intro b",
                "intro c",
                "intro d",
                "trans (b + a) + (c + d)",
                "congr",
                "apply add_comm",
                "refl",
                "trans (c + a) + (b + d)",
                "apply add_permute_outer",
                "congr",
                "apply add_comm",
                "refl",
                "have hbridge : "
                "((bn + cn) + outp) + (bcp + outn) = "
                "((bp + cp) + outn) + (bcn + outp)",
                "trans ((bn + cn) + bcp) + (outp + outn)",
                "apply hshuffle",
                "trans ((bp + cp) + bcn) + (outp + outn)",
                "congr",
                "symm",
                "exact hthird",
                "refl",
                "trans ((bp + cp) + bcn) + (outn + outp)",
                "congr",
                "refl",
                "apply add_comm",
                "apply hshuffle",
                "have hresult_flat : "
                "ap + (bcp + outn) = an + (bcn + outp)",
                "specialize add_cross_sum_chain ap",
                "specialize add_cross_sum_chain an",
                "specialize add_cross_sum_chain ((bp + cp) + outn)",
                "specialize add_cross_sum_chain ((bn + cn) + outp)",
                "specialize add_cross_sum_chain (bcp + outn)",
                "specialize add_cross_sum_chain (bcn + outp)",
                "apply add_cross_sum_chain",
                "exact htriple",
                "exact hbridge",
                "trans ap + (bcp + outn)",
                "apply add_assoc",
                "trans an + (bcn + outp)",
                "exact hresult_flat",
                "symm",
                "apply add_assoc",
            ),
            "The three decoded contribution equations for the two "
            "parenthesizations of a signed sum imply the target equation.",
        ),
        spec(
            "signed_add_associative",
            "forall a b c ab bc abc. "
            f"({add_ab}) -> ({add_abc}) -> ({add_bc}) -> ({add_target})",
            (
                "signed_add_to_decoded_equation",
                "signed_add_equations_associate",
                "signed_add_of_decoded_equation",
            ),
            (
                "intro a",
                "intro b",
                "intro c",
                "intro ab",
                "intro bc",
                "intro abc",
                "intro hab",
                "intro habc",
                "intro hbc",
                "cases hab",
                "cases hab_witness",
                "cases hab_witness_witness",
                "cases hab_witness_witness_witness",
                "cases hab_witness_witness_witness_witness",
                "cases hab_witness_witness_witness_witness_witness",
                "cases hab_witness_witness_witness_witness_witness_witness",
                "cases hab_witness_witness_witness_witness_witness_witness_right",
                "cases hab_witness_witness_witness_witness_witness_witness_right_right",
                "cases habc",
                "cases habc_witness",
                "cases habc_witness_witness",
                "cases habc_witness_witness_witness",
                "cases habc_witness_witness_witness_witness",
                "cases habc_witness_witness_witness_witness_witness",
                "cases habc_witness_witness_witness_witness_witness_witness",
                "cases habc_witness_witness_witness_witness_witness_witness_right",
                "cases habc_witness_witness_witness_witness_witness_witness_right_right",
                "cases hbc",
                "cases hbc_witness",
                "cases hbc_witness_witness",
                "cases hbc_witness_witness_witness",
                "cases hbc_witness_witness_witness_witness",
                "cases hbc_witness_witness_witness_witness_witness",
                "cases hbc_witness_witness_witness_witness_witness_witness",
                "cases hbc_witness_witness_witness_witness_witness_witness_right",
                "cases hbc_witness_witness_witness_witness_witness_witness_right_right",
                "have hequation_abc : "
                "(x4 + x8) + x11 = (x5 + x9) + x10",
                "specialize signed_add_to_decoded_equation ab",
                "specialize signed_add_to_decoded_equation c",
                "specialize signed_add_to_decoded_equation abc",
                "specialize signed_add_to_decoded_equation x4",
                "specialize signed_add_to_decoded_equation x5",
                "specialize signed_add_to_decoded_equation x8",
                "specialize signed_add_to_decoded_equation x9",
                "specialize signed_add_to_decoded_equation x10",
                "specialize signed_add_to_decoded_equation x11",
                "apply signed_add_to_decoded_equation",
                "exact hab_witness_witness_witness_witness_witness_witness_right_right_left",
                "exact habc_witness_witness_witness_witness_witness_witness_right_left",
                "exact habc_witness_witness_witness_witness_witness_witness_right_right_left",
                "exact habc",
                "have hequation_bc : "
                "(x2 + x8) + x17 = (x3 + x9) + x16",
                "specialize signed_add_to_decoded_equation b",
                "specialize signed_add_to_decoded_equation c",
                "specialize signed_add_to_decoded_equation bc",
                "specialize signed_add_to_decoded_equation x2",
                "specialize signed_add_to_decoded_equation x3",
                "specialize signed_add_to_decoded_equation x8",
                "specialize signed_add_to_decoded_equation x9",
                "specialize signed_add_to_decoded_equation x16",
                "specialize signed_add_to_decoded_equation x17",
                "apply signed_add_to_decoded_equation",
                "exact hab_witness_witness_witness_witness_witness_witness_right_left",
                "exact habc_witness_witness_witness_witness_witness_witness_right_left",
                "exact hbc_witness_witness_witness_witness_witness_witness_right_right_left",
                "exact hbc",
                "have htarget_equation : "
                "(x + x16) + x11 = (x1 + x17) + x10",
                "specialize signed_add_equations_associate x",
                "specialize signed_add_equations_associate x1",
                "specialize signed_add_equations_associate x2",
                "specialize signed_add_equations_associate x3",
                "specialize signed_add_equations_associate x8",
                "specialize signed_add_equations_associate x9",
                "specialize signed_add_equations_associate x4",
                "specialize signed_add_equations_associate x5",
                "specialize signed_add_equations_associate x16",
                "specialize signed_add_equations_associate x17",
                "specialize signed_add_equations_associate x10",
                "specialize signed_add_equations_associate x11",
                "apply signed_add_equations_associate",
                "exact hab_witness_witness_witness_witness_witness_witness_right_right_right",
                "exact hequation_abc",
                "exact hequation_bc",
                "specialize signed_add_of_decoded_equation a",
                "specialize signed_add_of_decoded_equation bc",
                "specialize signed_add_of_decoded_equation abc",
                "specialize signed_add_of_decoded_equation x",
                "specialize signed_add_of_decoded_equation x1",
                "specialize signed_add_of_decoded_equation x16",
                "specialize signed_add_of_decoded_equation x17",
                "specialize signed_add_of_decoded_equation x10",
                "specialize signed_add_of_decoded_equation x11",
                "apply signed_add_of_decoded_equation",
                "exact hab_witness_witness_witness_witness_witness_witness_left",
                "exact hbc_witness_witness_witness_witness_witness_witness_right_right_left",
                "exact habc_witness_witness_witness_witness_witness_witness_right_right_left",
                "exact htarget_equation",
            ),
            "Canonical signed addition is associative as a graph relation.",
        ),
    )


__all__ = ["make_ha_signed_add_associative_candidate_theorems"]
