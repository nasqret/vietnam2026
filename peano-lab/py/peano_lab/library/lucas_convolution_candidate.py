def _choose(upper: str, lower: str, value: str, *, tag: str) -> str:
    return _choose_relation_term(
        upper,
        lower,
        value,
        tag=f"lucas_convolution_{tag}",
        variables=("p", "n", "a", "b", "k", "j", "C", "D", "A", "B", "X", "Y"),
    )


def _lt(left: str, right: str, *, tag: str) -> str:
    return f"exists lcv_gap_{tag}. lcv_gap_{tag} + S ({left}) = ({right})"


def _mod(modulus: str, left: str, right: str, *, tag: str) -> str:
    return (
        f"exists lcv_left_{tag} lcv_right_{tag}. "
        f"({left}) + ({modulus}) * lcv_left_{tag} = "
        f"({right}) + ({modulus}) * lcv_right_{tag}"
    )


def _divides(divisor: str, value: str, *, tag: str) -> str:
    return f"exists lcv_quotient_{tag}. ({value}) = ({divisor}) * lcv_quotient_{tag}"


