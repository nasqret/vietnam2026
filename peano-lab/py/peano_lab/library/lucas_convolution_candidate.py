"""Constructive Pascal-convolution and prime-block congruence candidates.

All notation expands into ordinary first-order Heyting arithmetic.  These
isolated dependency-curried candidates neither add a polynomial primitive nor
modify the public registry or sealed Alpha/Stable editions.
"""

