def _lt(left: str, right: str, *, tag: str) -> str:
    return f"exists fsri_gap_{tag}. fsri_gap_{tag} + S ({left}) = ({right})"


def _le(left: str, right: str, *, tag: str) -> str:
    return f"exists fsri_gap_{tag}. fsri_gap_{tag} + ({left}) = ({right})"


def _mod(modulus: str, left: str, right: str, *, tag: str) -> str:
    return (
        f"exists fsri_left_{tag} fsri_right_{tag}. "
        f"({left}) + ({modulus}) * fsri_left_{tag} = "
        f"({right}) + ({modulus}) * fsri_right_{tag}"
    )


def _dvd(divisor: str, value: str, *, tag: str) -> str:
    return f"exists fsri_factor_{tag}. ({value}) = ({divisor}) * fsri_factor_{tag}"


def _beta(code: str, scale: str, index: str, value: str, *, tag: str) -> str:
    height = f"fsri_height_{tag}"
    quotient = f"fsri_quotient_{tag}"
    modulus = f"S ((S ({index})) * ({scale}))"
    return (
        f"((exists {height}. {height} + S ({value}) = {modulus}) /\\ "
        f"exists {quotient}. ({code}) = {quotient} * {modulus} + ({value}))"
    )


def square_residue_prefix(
    modulus: str,
    code: str,
    scale: str,
    length: str,
    *,
    tag: str,
) -> str:
    """Expand a beta-coded prefix of canonical square residues."""

    index = f"fsri_index_{tag}"
    quotient = f"fsri_quotient_{tag}"
    residue = f"fsri_residue_{tag}"
    return (
        f"forall {index}. ({_lt(index, length, tag=f'{tag}_index')}) -> "
        f"exists {quotient} {residue}. "
        f"({index} * {index} = ({modulus}) * {quotient} + {residue} /\\ "
        f"(({_lt(residue, modulus, tag=f'{tag}_residue')}) /\\ "
        f"({_beta(code, scale, index, residue, tag=f'{tag}_entry')})))"
    )


def complement_residue_prefix(
    modulus: str,
    source_code: str,
    source_scale: str,
    target_code: str,
    target_scale: str,
    length: str,
    *,
    tag: str,
) -> str:
    """Expand the beta-coded map r ↦ p-1-r without natural subtraction."""

    index = f"fsri_complement_index_{tag}"
    source = f"fsri_complement_source_{tag}"
    target = f"fsri_complement_target_{tag}"
    return (
        f"forall {index} {source} {target}. "
        f"({_lt(index, length, tag=f'{tag}_index')}) -> "
        f"({_beta(source_code, source_scale, index, source, tag=f'{tag}_source')}) -> "
        f"({_beta(target_code, target_scale, index, target, tag=f'{tag}_target')}) -> "
        f"{target} + S {source} = ({modulus})"
    )


