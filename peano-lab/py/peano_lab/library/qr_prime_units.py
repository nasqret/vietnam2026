"""Constructive prime-unit prerequisites for quadratic reciprocity.

The public contracts in this module deliberately expand ``Prime``,
``Coprime``, divisibility, and balanced congruence into the unchanged
first-order PA language.  The module exports a theorem-spec factory rather
than registering its tranche; integration into the main ladder is a separate
review step.
"""

from __future__ import annotations

from typing import Any, Callable


PRIME_P = "(~(p = 1) /\\ forall c e. p = c * e -> c = 1 \\/ e = 1)"
PRIME_Q = "(~(q = 1) /\\ forall c e. q = c * e -> c = 1 \\/ e = 1)"
COPRIME_P_A = (
    "forall d. (exists x. p = d * x) -> (exists y. a = d * y) -> d = 1"
)
COPRIME_A_M = (
    "forall d. (exists x. a = d * x) -> (exists y. m = d * y) -> d = 1"
)


def make_qr_prime_unit_theorems(
    spec: Callable[..., Any],
) -> tuple[Any, ...]:
    """Build a dependency-ordered constructive prime/unit tranche."""

    return (
        spec(
            "prime_coprime_or_divides",
            f"forall p a. {PRIME_P} -> ({COPRIME_P_A}) \\/ "
            "exists k. a = p * k",
            (
                "gcd_exists_relational",
                "prime_divisor_eq_one_or_self",
                "is_gcd_one_to_coprime",
            ),
            (
                "intro p",
                "intro a",
                "intro hp",
                "have hg : exists g. (((exists x. p = g * x) /\\ "
                "(exists y. a = g * y)) /\\ forall c. "
                "(exists u. p = c * u) -> (exists v. a = c * v) -> "
                "exists w. g = c * w)",
                "apply gcd_exists_relational",
                "cases hg",
                "have hgfull : (((exists u. p = x * u) /\\ "
                "(exists v. a = x * v)) /\\ forall c. "
                "(exists s. p = c * s) -> (exists t. a = c * t) -> "
                "exists w. x = c * w)",
                "exact hg_witness",
                "cases hg_witness",
                "cases hg_witness_left",
                "have hfactor : x = 1 \\/ p = x",
                "specialize prime_divisor_eq_one_or_self p",
                "specialize prime_divisor_eq_one_or_self x",
                "apply prime_divisor_eq_one_or_self",
                "exact hp",
                "exact hg_witness_left_left",
                "cases hfactor",
                "left",
                "apply is_gcd_one_to_coprime",
                "have hg1 : (((exists u. p = 1 * u) /\\ "
                "(exists v. a = 1 * v)) /\\ forall c. "
                "(exists s. p = c * s) -> (exists t. a = c * t) -> "
                "exists w. 1 = c * w)",
                "rewrite <- hfactor_left",
                "rewrite <- hfactor_left",
                "rewrite <- hfactor_left",
                "exact hgfull",
                "exact hg1",
                "right",
                "cases hg_witness_left_right",
                "exists x1",
                "rewrite hfactor_right",
                "exact hg_witness_left_right_witness",
            ),
            "A prime is constructively either coprime to a natural or divides it.",
        ),
        spec(
            "prime_not_divides_coprime",
            f"forall p a. {PRIME_P} -> ~(exists k. a = p * k) -> "
            f"{COPRIME_P_A}",
            ("prime_coprime_or_divides",),
            (
                "intro p",
                "intro a",
                "intro hp",
                "intro hnot",
                "specialize prime_coprime_or_divides p",
                "specialize prime_coprime_or_divides a",
                "have hsplit : (forall d. (exists x. p = d * x) -> "
                "(exists y. a = d * y) -> d = 1) \\/ "
                "exists k. a = p * k",
                "apply prime_coprime_or_divides",
                "exact hp",
                "cases hsplit",
                "exact hsplit_left",
                "exfalso",
                "apply hnot",
                "exact hsplit_right",
            ),
            "A prime not dividing a natural is coprime to that natural.",
        ),
        spec(
            "distinct_primes_coprime",
            f"forall p q. {PRIME_P} -> {PRIME_Q} -> ~(p = q) -> "
            "forall d. (exists x. p = d * x) -> "
            "(exists y. q = d * y) -> d = 1",
            ("prime_divisor_eq_one_or_self", "prime_not_divides_coprime"),
            (
                "intro p",
                "intro q",
                "intro hp",
                "intro hq",
                "intro hpq",
                "have hnot : ~(exists k. q = p * k)",
                "intro hdiv",
                "specialize prime_divisor_eq_one_or_self q",
                "specialize prime_divisor_eq_one_or_self p",
                "have hfactor : p = 1 \\/ q = p",
                "apply prime_divisor_eq_one_or_self",
                "exact hq",
                "exact hdiv",
                "cases hfactor",
                "cases hp",
                "apply hp_left",
                "exact hfactor_left",
                "apply hpq",
                "symm",
                "exact hfactor_right",
                "specialize prime_not_divides_coprime p",
                "specialize prime_not_divides_coprime q",
                "apply prime_not_divides_coprime",
                "exact hp",
                "exact hnot",
            ),
            "Distinct primes are coprime in the expanded common-divisor relation.",
        ),
        spec(
            "coprime_balanced_mod_inverse",
            f"forall a m. ({COPRIME_A_M}) -> exists xp xn u v. "
            "a * xp + m * u = (1 + a * xn) + m * v",
            ("coprime_balanced_bezout", "add_assoc"),
            (
                "intro a",
                "intro m",
                "intro hcop",
                "have hbez : exists xp yp xn yn. "
                "a * xp + m * yp = 1 + (a * xn + m * yn)",
                "specialize coprime_balanced_bezout a",
                "specialize coprime_balanced_bezout m",
                "apply coprime_balanced_bezout",
                "exact hcop",
                "cases hbez",
                "cases hbez_witness",
                "cases hbez_witness_witness",
                "cases hbez_witness_witness_witness",
                "exists x",
                "exists x2",
                "exists x1",
                "exists x3",
                "trans 1 + (a * x2 + m * x3)",
                "exact hbez_witness_witness_witness_witness",
                "symm",
                "apply add_assoc",
            ),
            "Balanced Bezout coefficients give a subtraction-free modular inverse.",
        ),
        spec(
            "coprime_mod_inverse",
            f"forall a m. ~(m = 0) -> ({COPRIME_A_M}) -> "
            "exists z u v. a * z + m * u = 1 + m * v",
            (
                "nonzero_is_succ",
                "coprime_balanced_mod_inverse",
                "mod_eq_refl",
                "mod_eq_add",
                "mod_eq_predecessor_cancel",
                "mod_eq_trans",
                "mul_add",
                "mul_assoc",
                "mul_comm",
            ),
            (
                "intro a",
                "intro m",
                "intro hm",
                "intro hcop",
                "have hms : exists k. m = S k",
                "specialize nonzero_is_succ m",
                "apply nonzero_is_succ",
                "exact hm",
                "have hbal : exists xp xn u v. "
                "a * xp + m * u = (1 + a * xn) + m * v",
                "specialize coprime_balanced_mod_inverse a",
                "specialize coprime_balanced_mod_inverse m",
                "apply coprime_balanced_mod_inverse",
                "exact hcop",
                "cases hms",
                "cases hbal",
                "cases hbal_witness",
                "cases hbal_witness_witness",
                "cases hbal_witness_witness_witness",
                "have hself : exists u v. (x * (a * x2)) + m * u = "
                "(x * (a * x2)) + m * v",
                "specialize mod_eq_refl m",
                "specialize mod_eq_refl (x * (a * x2))",
                "apply mod_eq_refl",
                "have hadd : exists u v. ((a * x1) + x * (a * x2)) + m * u = "
                "((1 + a * x2) + x * (a * x2)) + m * v",
                "specialize mod_eq_add m",
                "specialize mod_eq_add (a * x1)",
                "specialize mod_eq_add (1 + a * x2)",
                "specialize mod_eq_add (x * (a * x2))",
                "specialize mod_eq_add (x * (a * x2))",
                "apply mod_eq_add",
                "exists x3",
                "exists x4",
                "exact hbal_witness_witness_witness_witness",
                "exact hself",
                "have hcancel : exists u v. "
                "((1 + a * x2) + x * (a * x2)) + m * u = 1 + m * v",
                "specialize mod_eq_predecessor_cancel x",
                "specialize mod_eq_predecessor_cancel 1",
                "specialize mod_eq_predecessor_cancel (a * x2)",
                "have hkcancel : exists u v. "
                "((1 + a * x2) + x * (a * x2)) + S x * u = "
                "1 + S x * v",
                "apply mod_eq_predecessor_cancel",
                "rewrite <- hms_witness at hkcancel",
                "rewrite <- hms_witness at hkcancel",
                "exact hkcancel",
                "have hfinal : exists u v. "
                "((a * x1) + x * (a * x2)) + m * u = 1 + m * v",
                "specialize mod_eq_trans m",
                "specialize mod_eq_trans ((a * x1) + x * (a * x2))",
                "specialize mod_eq_trans ((1 + a * x2) + x * (a * x2))",
                "specialize mod_eq_trans 1",
                "apply mod_eq_trans",
                "exact hadd",
                "exact hcancel",
                "have hnorm : a * (x1 + x * x2) = "
                "(a * x1) + x * (a * x2)",
                "trans a * x1 + a * (x * x2)",
                "apply mul_add",
                "congr",
                "refl",
                "trans (a * x) * x2",
                "symm",
                "apply mul_assoc",
                "trans (x * a) * x2",
                "congr",
                "apply mul_comm",
                "refl",
                "apply mul_assoc",
                "exists x1 + x * x2",
                "rewrite hnorm",
                "exact hfinal",
            ),
            "A nonzero modulus turns balanced Bezout data into a natural modular inverse.",
        ),
        spec(
            "mod_eq_cancel_coprime",
            f"forall m a x y. ~(m = 0) -> ({COPRIME_A_M}) -> "
            "(exists u v. (a * x) + m * u = (a * y) + m * v) -> "
            "exists r s. x + m * r = y + m * s",
            (
                "coprime_mod_inverse",
                "mod_eq_mul_right",
                "mod_eq_mul_left",
                "mod_eq_symm",
                "mod_eq_trans",
                "mul_assoc",
                "mul_comm",
                "mul_one",
            ),
            (
                "intro m",
                "intro a",
                "intro x",
                "intro y",
                "intro hm",
                "intro hcop",
                "intro hxy",
                "have hinv : exists z u v. a * z + m * u = 1 + m * v",
                "specialize coprime_mod_inverse a",
                "specialize coprime_mod_inverse m",
                "apply coprime_mod_inverse",
                "exact hm",
                "exact hcop",
                "cases hinv",
                "cases hinv_witness",
                "cases hinv_witness_witness",
                "have hzx : exists u v. (x * (a * x1)) + m * u = "
                "(x * 1) + m * v",
                "specialize mod_eq_mul_left m",
                "specialize mod_eq_mul_left (a * x1)",
                "specialize mod_eq_mul_left 1",
                "specialize mod_eq_mul_left x",
                "apply mod_eq_mul_left",
                "exists x2",
                "exists x3",
                "exact hinv_witness_witness_witness",
                "have hnormx : x * (a * x1) = (a * x) * x1",
                "trans (x * a) * x1",
                "symm",
                "apply mul_assoc",
                "trans (a * x) * x1",
                "congr",
                "apply mul_comm",
                "refl",
                "refl",
                "have honex : x * 1 = x",
                "apply mul_one",
                "have hxprod : exists u v. ((a * x) * x1) + m * u = x + m * v",
                "cases hzx",
                "cases hzx_witness",
                "exists x4",
                "exists x5",
                "trans (x * (a * x1)) + m * x4",
                "congr",
                "symm",
                "exact hnormx",
                "refl",
                "trans (x * 1) + m * x5",
                "exact hzx_witness_witness",
                "congr",
                "exact honex",
                "refl",
                "have hxhprod : exists u v. x + m * u = ((a * x) * x1) + m * v",
                "specialize mod_eq_symm m",
                "specialize mod_eq_symm ((a * x) * x1)",
                "specialize mod_eq_symm x",
                "apply mod_eq_symm",
                "exact hxprod",
                "have hscaled : exists u v. ((a * x) * x1) + m * u = "
                "((a * y) * x1) + m * v",
                "specialize mod_eq_mul_right m",
                "specialize mod_eq_mul_right (a * x)",
                "specialize mod_eq_mul_right (a * y)",
                "specialize mod_eq_mul_right x1",
                "apply mod_eq_mul_right",
                "exact hxy",
                "have hzy : exists u v. (y * (a * x1)) + m * u = "
                "(y * 1) + m * v",
                "specialize mod_eq_mul_left m",
                "specialize mod_eq_mul_left (a * x1)",
                "specialize mod_eq_mul_left 1",
                "specialize mod_eq_mul_left y",
                "apply mod_eq_mul_left",
                "exists x2",
                "exists x3",
                "exact hinv_witness_witness_witness",
                "have hnormy : y * (a * x1) = (a * y) * x1",
                "trans (y * a) * x1",
                "symm",
                "apply mul_assoc",
                "trans (a * y) * x1",
                "congr",
                "apply mul_comm",
                "refl",
                "refl",
                "have honey : y * 1 = y",
                "apply mul_one",
                "have hyprod : exists u v. ((a * y) * x1) + m * u = y + m * v",
                "cases hzy",
                "cases hzy_witness",
                "exists x4",
                "exists x5",
                "trans (y * (a * x1)) + m * x4",
                "congr",
                "symm",
                "exact hnormy",
                "refl",
                "trans (y * 1) + m * x5",
                "exact hzy_witness_witness",
                "congr",
                "exact honey",
                "refl",
                "have hmid : exists u v. x + m * u = ((a * y) * x1) + m * v",
                "specialize mod_eq_trans m",
                "specialize mod_eq_trans x",
                "specialize mod_eq_trans ((a * x) * x1)",
                "specialize mod_eq_trans ((a * y) * x1)",
                "apply mod_eq_trans",
                "exact hxhprod",
                "exact hscaled",
                "specialize mod_eq_trans m",
                "specialize mod_eq_trans x",
                "specialize mod_eq_trans ((a * y) * x1)",
                "specialize mod_eq_trans y",
                "apply mod_eq_trans",
                "exact hmid",
                "exact hyprod",
            ),
            "A coprime factor cancels from balanced congruence at nonzero modulus.",
        ),
        spec(
            "prime_mod_inverse",
            f"forall p a. {PRIME_P} -> ~(exists k. a = p * k) -> "
            "exists z u v. a * z + p * u = 1 + p * v",
            (
                "prime_nonzero",
                "prime_not_divides_coprime",
                "coprime_mod_inverse",
            ),
            (
                "intro p",
                "intro a",
                "intro hp",
                "intro hnot",
                "have hp0 : ~(p = 0)",
                "intro hpzero",
                "specialize prime_nonzero p",
                "apply prime_nonzero",
                "exact hp",
                "exact hpzero",
                "have hcop : forall d. (exists x. a = d * x) -> "
                "(exists y. p = d * y) -> d = 1",
                "have hpacop : forall d. (exists x. p = d * x) -> "
                "(exists y. a = d * y) -> d = 1",
                "specialize prime_not_divides_coprime p",
                "specialize prime_not_divides_coprime a",
                "apply prime_not_divides_coprime",
                "exact hp",
                "exact hnot",
                "intro d",
                "intro hda",
                "intro hdp",
                "specialize hpacop d",
                "apply hpacop",
                "exact hdp",
                "exact hda",
                "specialize coprime_mod_inverse a",
                "specialize coprime_mod_inverse p",
                "apply coprime_mod_inverse",
                "exact hp0",
                "exact hcop",
            ),
            "A nonzero residue modulo a prime has a natural modular inverse.",
        ),
        spec(
            "prime_mod_cancel",
            f"forall p a x y. {PRIME_P} -> "
            "~(exists k. a = p * k) -> "
            "(exists u v. (a * x) + p * u = (a * y) + p * v) -> "
            "exists r s. x + p * r = y + p * s",
            (
                "prime_nonzero",
                "prime_not_divides_coprime",
                "coprime_symm",
                "mod_eq_cancel_coprime",
            ),
            (
                "intro p",
                "intro a",
                "intro x",
                "intro y",
                "intro hp",
                "intro hnot",
                "intro hxy",
                "have hp0 : ~(p = 0)",
                "intro hpzero",
                "specialize prime_nonzero p",
                "apply prime_nonzero",
                "exact hp",
                "exact hpzero",
                "have hpacop : forall d. (exists u. p = d * u) -> "
                "(exists v. a = d * v) -> d = 1",
                "specialize prime_not_divides_coprime p",
                "specialize prime_not_divides_coprime a",
                "apply prime_not_divides_coprime",
                "exact hp",
                "exact hnot",
                "have hapcop : forall d. (exists u. a = d * u) -> "
                "(exists v. p = d * v) -> d = 1",
                "specialize coprime_symm p",
                "specialize coprime_symm a",
                "apply coprime_symm",
                "exact hpacop",
                "specialize mod_eq_cancel_coprime p",
                "specialize mod_eq_cancel_coprime a",
                "specialize mod_eq_cancel_coprime x",
                "specialize mod_eq_cancel_coprime y",
                "apply mod_eq_cancel_coprime",
                "exact hp0",
                "exact hapcop",
                "exact hxy",
            ),
            "A nonzero residue factor cancels from congruence modulo a prime.",
        ),
    )


