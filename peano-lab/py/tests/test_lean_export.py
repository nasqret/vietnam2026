def test_export_value_and_argument_contracts_are_immutable_and_explicit() -> None:
    exported = export_theorem("refl_zero", parse_formula("0 = 0"))
    assert "--   (no script supplied)" in exported.code

    with pytest.raises(FrozenInstanceError):
        exported.code = "changed"  # type: ignore[misc]
    with pytest.raises(TypeError, match="script"):
        export_theorem("refl_zero", parse_formula("0 = 0"), [1])  # type: ignore[list-item]
    for malformed in (
        "zero_add",
        b"",
        b"zero_add",
        bytearray(),
        [1],
        ("zero_add", 1),
    ):
        with pytest.raises(TypeError, match="dependencies"):
            export_theorem(
                "refl_zero",
                parse_formula("0 = 0"),
                dependencies=malformed,  # type: ignore[arg-type]
            )
    with pytest.raises(TypeError, match="text"):
        live_lean_url(None)  # type: ignore[arg-type]
